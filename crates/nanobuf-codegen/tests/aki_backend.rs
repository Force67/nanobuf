use nanobuf_codegen::{GeneratedFile, Lang};
use nanobuf_diagnostics::{Diagnostics, SourceMap};
use nanobuf_schema::Unit;

/// Generates aki for one or more `(file name, text)` schema units.
fn generate_aki_units(files: &[(&str, &str)]) -> Vec<GeneratedFile> {
    let mut sources = SourceMap::new();
    let mut diags = Diagnostics::new();
    let mut units = Vec::new();
    for (name, text) in files {
        let file = sources.add(*name, *text);
        let ast = nanobuf_syntax::parse(file, text, &mut diags).unwrap();
        units.push(Unit { file, ast });
    }
    let schema = nanobuf_schema::analyze(&units, &mut diags)
        .unwrap_or_else(|| panic!("{}", diags.render(&sources, false)));
    nanobuf_codegen::generate(&schema, Lang::Aki, "out").unwrap()
}

/// Generated text of the single package in `text`.
fn generate_aki(text: &str) -> String {
    let mut files = generate_aki_units(&[("t.nb", text)]);
    assert_eq!(files.len(), 1);
    files.remove(0).content
}

#[test]
fn output_is_deterministic() {
    let text = "schema a\nmessage M {\n  x: u32 @1\n  s: string @2\n}\n";
    assert_eq!(generate_aki(text), generate_aki(text));
}

#[test]
fn generates_expected_api_surface() {
    let code = generate_aki(
        "schema demo.telemetry\nenum Status: u8 {\n  unknown = 0\n  ok = 1\n}\nmessage Packet {\n  status: Status @1\n  name: string @2\n  maybe: f64? @3\n}\n",
    );
    for expected in [
        "// @generated by nanoc. DO NOT EDIT.",
        "module demo::telemetry;",
        "import {DecodeError} from nanobuf::error;",
        "import {View, OffsetList} from nanobuf::view;",
        "import {Writer} from nanobuf::writer;",
        "pub open enum Status as u8 {",
        "Unknown = 0,",
        "Ok = 1,",
        "pub fn status_name(value: Status): str? => match (value) {",
        "pub struct Packet : Equal {",
        "pub var status: Status = 0 as Status;",
        "pub var name: String = String();",
        "pub var maybe: f64? = none;",
        "pub fn encode(self&): List<u8>;",
        "pub fn encode_proto3(self&): List<u8>;",
        "pub fn decode(data: &[u8]): Packet ! DecodeError;",
        "pub fn decode_proto3(data: &[u8]): Packet ! DecodeError;",
        "pub struct PacketView<'a> : Copy {",
        "pub let view: View<'a>",
        "pub fn parse(data: &'a [u8]): PacketView<'a> ! DecodeError;",
        "pub fn name(self&): str<'a> ! DecodeError;",
        "pub fn maybe(self&): f64?;",
        "pub fn to_owned(self&): Packet ! DecodeError;",
        "fn Packet::write_to(self&, var w&: Writer) {",
        "fn PacketView::to_owned(self&): Packet ! DecodeError {",
    ] {
        assert!(code.contains(expected), "missing `{expected}` in:\n{code}");
    }
}

#[test]
fn doc_comments_are_carried_through() {
    let code = generate_aki(
        "schema a\n/// The packet.\nmessage Packet {\n  /// Field doc.\n  x: u32 @1\n}\n",
    );
    assert!(code.contains("/// The packet."), "{code}");
    assert!(code.contains("/// Field doc."), "{code}");
}

#[test]
fn keyword_field_names_are_escaped() {
    let code = generate_aki("schema a\nmessage M {\n  match: u32 @1\n  open: bool @2\n}\n");
    assert!(code.contains("pub var match_: u32 = 0;"), "{code}");
    assert!(code.contains("pub var open_: bool = false;"), "{code}");
}

#[test]
fn reserved_view_method_names_get_prefixed() {
    let code = generate_aki("schema a\nmessage M {\n  data: bytes @1\n  size: u32 @2\n}\n");
    assert!(
        code.contains("pub fn get_data(self&): &'a [u8] ! DecodeError;"),
        "{code}"
    );
    assert!(code.contains("pub fn get_size(self&): u32;"), "{code}");
    // The owned struct keeps the plain field names.
    assert!(
        code.contains("pub var data: List<u8> = List::<u8>();"),
        "{code}"
    );
}

#[test]
fn recursive_fields_are_boxed() {
    let code = generate_aki("schema a\nmessage Tree {\n  left: Tree @1\n}\n");
    assert!(code.contains("pub var left: Box<Tree>? = none;"), "{code}");
    assert!(
        code.contains("!same_boxed(self.left, other.left)"),
        "{code}"
    );
}

#[test]
fn bool_list_elements_are_one_byte() {
    let code = generate_aki("schema a\nmessage M {\n  flags: list<bool> @1\n}\n");
    assert!(
        code.contains("w.begin_scalar_list(self.flags.len(), 1);"),
        "{code}"
    );
    assert!(
        code.contains("ScalarList<'a, bool> ! DecodeError"),
        "{code}"
    );
}

#[test]
fn cross_package_references_use_module_paths() {
    let files = generate_aki_units(&[
        (
            "common.nb",
            "schema common\n/// Origin of a packet.\nmessage Header {\n  source: u32 @1\n}\n",
        ),
        (
            "telemetry.nb",
            "schema demo.telemetry\nimport \"common.nb\"\nmessage Packet {\n  header: common.Header @1\n  headers: list<common.Header> @2\n}\n",
        ),
    ]);
    let names: Vec<&str> = files.iter().map(|f| f.name.as_str()).collect();
    assert_eq!(names, ["common.aki", "demo_telemetry.aki"]);

    let telemetry = &files[1].content;
    assert!(telemetry.contains("module demo::telemetry;"), "{telemetry}");
    assert!(telemetry.contains("import common;"), "{telemetry}");
    assert!(
        telemetry.contains("pub var header: common::Header? = none;"),
        "{telemetry}"
    );
    assert!(
        telemetry.contains("pub var headers: List<common::Header> = List::<common::Header>();"),
        "{telemetry}"
    );
    assert!(
        telemetry.contains("common::HeaderViewList<'a>"),
        "{telemetry}"
    );

    let common = &files[0].content;
    assert!(common.contains("module common;"), "{common}");
    assert!(!common.contains("import demo::telemetry;"), "{common}");
    // The dependency's struct is declared in its own module.
    assert!(common.contains("/// Origin of a packet."), "{common}");
}

#[test]
fn unused_runtime_names_are_not_imported() {
    let code = generate_aki("schema a\nmessage M {\n  x: u32 @1\n}\n");
    assert!(!code.contains("import {Float16"), "{code}");
    assert!(!code.contains("akikit::memory::box"), "{code}");
    // Every message carries proto3 codecs, so the proto module is always used.
    assert!(code.contains("from nanobuf::proto;"), "{code}");
    assert!(
        code.contains("import {Writer} from nanobuf::writer;"),
        "{code}"
    );
}

#[test]
fn output_has_no_stacked_blank_lines() {
    let code = generate_aki(
        "schema demo.telemetry\nenum Status: u8 {\n  ok = 0\n}\nmessage A {\n  x: u32 @1\n}\nmessage B {\n  a: A @1\n}\n",
    );
    assert!(!code.contains("\n\n\n"), "{code}");
    assert!(code.ends_with("}\n"), "{code}");
}
