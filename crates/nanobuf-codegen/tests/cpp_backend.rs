use nanobuf_diagnostics::{Diagnostics, SourceMap};
use nanobuf_schema::Unit;

fn generate_cpp(text: &str) -> String {
    let mut sources = SourceMap::new();
    let mut diags = Diagnostics::new();
    let file = sources.add("t.nb", text);
    let ast = nanobuf_syntax::parse(file, text, &mut diags).unwrap();
    let schema = nanobuf_schema::analyze(&[Unit { file, ast }], &mut diags)
        .unwrap_or_else(|| panic!("{}", diags.render(&sources, false)));
    let files = nanobuf_codegen::generate(&schema, nanobuf_codegen::Lang::Cpp, "out").unwrap();
    assert_eq!(files.len(), 1);
    assert_eq!(files[0].name, "out.nb.h");
    files[0].content.clone()
}

#[test]
fn output_is_deterministic() {
    let text = "schema a\nmessage M {\n  x: u32 @1\n  s: string @2\n}\n";
    assert_eq!(generate_cpp(text), generate_cpp(text));
}

#[test]
fn generates_expected_api_surface() {
    let code = generate_cpp(
        "schema demo.telemetry\nenum Status: u8 {\n  unknown = 0\n  ok = 1\n}\nmessage Packet {\n  status: Status @1\n  name: string @2\n  maybe: f64? @3\n}\n",
    );
    for expected in [
        "// @generated by nanoc. DO NOT EDIT.",
        "#pragma once",
        "#include \"nanobuf.h\"",
        "namespace demo::telemetry {",
        "struct Status {",
        "static const Status kOk;",
        "inline constexpr Status Status::kOk{1};",
        "struct Packet {",
        "Status status;",
        "std::optional<double> maybe;",
        "std::vector<uint8_t> Encode() const;",
        "static std::optional<Packet> Decode(const uint8_t* data, size_t size);",
        "std::vector<uint8_t> EncodeProto3() const;",
        "static std::optional<Packet> DecodeProto3(const uint8_t* data, size_t size);",
        "class PacketView {",
        "static std::optional<PacketView> Parse(const uint8_t* data, size_t size);",
        "std::optional<Packet> ToOwned() const;",
        "inline std::vector<uint8_t> Packet::Encode() const {",
    ] {
        assert!(code.contains(expected), "missing `{expected}` in:\n{code}");
    }
}

#[test]
fn doc_comments_are_carried_through() {
    let code = generate_cpp(
        "schema a\n/// The packet.\nmessage Packet {\n  /// Field doc.\n  x: u32 @1\n}\n",
    );
    assert!(code.contains("// The packet."));
    assert!(code.contains("// Field doc."));
}

#[test]
fn keyword_field_names_are_escaped() {
    let code = generate_cpp("schema a\nmessage M {\n  template: u32 @1\n  operator: bool @2\n}\n");
    assert!(code.contains("uint32_t template_ = 0;"), "{code}");
    assert!(code.contains("bool operator_ = false;"), "{code}");
    assert!(code.contains("uint32_t template_() const;"), "{code}");
}

#[test]
fn reserved_view_method_names_get_prefixed() {
    let code = generate_cpp("schema a\nmessage M {\n  data: bytes @1\n  size: u32 @2\n}\n");
    assert!(code.contains("get_data() const;"), "{code}");
    assert!(code.contains("get_size() const;"), "{code}");
    // The owned struct keeps the plain field names.
    assert!(code.contains("std::vector<uint8_t> data;"), "{code}");
}

#[test]
fn recursive_fields_are_boxed() {
    let code = generate_cpp("schema a\nmessage Tree {\n  left: Tree @1\n}\n");
    assert!(code.contains("std::unique_ptr<Tree> left;"), "{code}");
    // Equality compares through the pointer.
    assert!(
        code.contains("if (a.left && !(*a.left == *b.left)) {"),
        "{code}"
    );
}

#[test]
fn cross_package_references_are_fully_qualified() {
    let mut sources = SourceMap::new();
    let mut diags = Diagnostics::new();
    let common = "schema common\nmessage Header {\n  source: u32 @1\n}\n";
    let main = "schema demo.telemetry\nimport \"common.nb\"\nmessage Packet {\n  header: common.Header @1\n}\n";
    let common_file = sources.add("common.nb", common);
    let main_file = sources.add("telemetry.nb", main);
    let units = [
        Unit {
            file: common_file,
            ast: nanobuf_syntax::parse(common_file, common, &mut diags).unwrap(),
        },
        Unit {
            file: main_file,
            ast: nanobuf_syntax::parse(main_file, main, &mut diags).unwrap(),
        },
    ];
    let schema = nanobuf_schema::analyze(&units, &mut diags)
        .unwrap_or_else(|| panic!("{}", diags.render(&sources, false)));
    let files = nanobuf_codegen::generate(&schema, nanobuf_codegen::Lang::Cpp, "out").unwrap();
    let code = &files[0].content;
    assert!(code.contains("namespace demo::telemetry {"), "{code}");
    assert!(
        code.contains("std::optional<::common::Header> header;"),
        "{code}"
    );
    // The dependency is defined before its use.
    let header_def = code.find("struct Header {").unwrap();
    let packet_def = code.find("struct Packet {").unwrap();
    assert!(header_def < packet_def, "{code}");
}
