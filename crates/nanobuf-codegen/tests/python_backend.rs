use nanobuf_diagnostics::{Diagnostics, SourceMap};
use nanobuf_schema::Unit;

fn generate_python_units(files: &[(&str, &str)]) -> String {
    let mut sources = SourceMap::new();
    let mut diags = Diagnostics::new();
    let mut units = Vec::new();
    for (name, text) in files {
        let file = sources.add(*name, *text);
        let ast = nanobuf_syntax::parse(file, text, &mut diags).unwrap();
        units.push(Unit { file, ast });
    }
    let schema = nanobuf_schema::analyze(&units, &mut diags)
        .unwrap_or_else(|| panic!("{}", diags.render(&sources, false)));
    let files = nanobuf_codegen::generate(&schema, nanobuf_codegen::Lang::Python, "out").unwrap();
    assert_eq!(files.len(), 1);
    assert_eq!(files[0].name, "out.py");
    files[0].content.clone()
}

fn generate_python(text: &str) -> String {
    generate_python_units(&[("t.nb", text)])
}

#[test]
fn output_is_deterministic() {
    let text = "schema a\nmessage M {\n  x: u32 @1\n  s: string @2\n}\n";
    assert_eq!(generate_python(text), generate_python(text));
}

#[test]
fn generates_expected_api_surface() {
    let code = generate_python(
        "schema demo\nenum Status: u8 {\n  unknown = 0\n  ok = 1\n}\nmessage Packet {\n  status: Status @1\n  name: string @2\n  maybe: f64? @3\n}\n",
    );
    for expected in [
        "# @generated by nanoc. DO NOT EDIT.",
        "import nanobuf",
        "class Status(int):",
        "def label(self):",
        "Status.UNKNOWN = Status(0)",
        "Status.OK = Status(1)",
        "class Packet:",
        "status=Status(0),",
        "maybe=None,",
        "def encode(self):",
        "def decode(cls, data):",
        "def encode_proto3(self):",
        "def decode_proto3(cls, data):",
        "class PacketView:",
        "def to_owned(self):",
    ] {
        assert!(code.contains(expected), "missing `{expected}` in:\n{code}");
    }
}

#[test]
fn doc_comments_become_docstrings() {
    let code = generate_python(
        "schema a\n/// The packet.\nmessage Packet {\n  /// Field doc.\n  x: u32 @1\n}\n",
    );
    assert!(code.contains("\"\"\"The packet.\"\"\""), "{code}");
    assert!(code.contains("\"\"\"Field doc.\"\"\""), "{code}");
}

#[test]
fn keyword_field_names_are_escaped() {
    let code = generate_python("schema a\nmessage M {\n  class: u32 @1\n  lambda: bool @2\n}\n");
    assert!(code.contains("self.class_ = class_"), "{code}");
    assert!(code.contains("self.lambda_ = lambda_"), "{code}");
}

#[test]
fn reserved_view_attrs_get_prefixed() {
    let code = generate_python("schema a\nmessage M {\n  data: bytes @1\n  to_owned: u32 @2\n}\n");
    assert!(code.contains("def get_data(self):"), "{code}");
    assert!(code.contains("def get_to_owned(self):"), "{code}");
    // The owned class keeps the plain field names.
    assert!(code.contains("self.data = data"), "{code}");
}

#[test]
fn colliding_type_names_get_package_prefixes() {
    let code = generate_python_units(&[
        ("a.nb", "schema demo.alpha\nmessage Dup {\n  x: u32 @1\n}\n"),
        (
            "b.nb",
            "schema beta\nmessage Dup {\n  y: u32 @1\n}\nmessage Solo {\n  d: Dup @2\n}\n",
        ),
    ]);
    assert!(code.contains("class DemoAlphaDup:"), "{code}");
    assert!(code.contains("class BetaDup:"), "{code}");
    // Unique names stay bare, and references use the prefixed name.
    assert!(code.contains("class Solo:"), "{code}");
    assert!(code.contains("BetaDupView(view)"), "{code}");
}

#[test]
fn generated_module_parses_as_python() {
    // Sanity-check the emitted syntax when an interpreter is available.
    let code = generate_python(
        "schema demo\nenum E: i32 {\n  a = -1\n}\nmessage M {\n  e: E @1\n  ns: list<i64> @2\n  child: M @3\n}\n",
    );
    let dir = std::env::temp_dir().join("nanobuf_python_backend_test");
    std::fs::create_dir_all(&dir).unwrap();
    let path = dir.join("out.py");
    std::fs::write(&path, &code).unwrap();
    let status = std::process::Command::new("python3")
        .arg("-c")
        .arg(format!(
            "import ast, pathlib; ast.parse(pathlib.Path({path:?}).read_text())"
        ))
        .status();
    if let Ok(status) = status {
        assert!(
            status.success(),
            "generated module has syntax errors:\n{code}"
        );
    }
}
