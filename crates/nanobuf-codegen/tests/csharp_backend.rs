use nanobuf_diagnostics::{Diagnostics, SourceMap};
use nanobuf_schema::Unit;

fn generate_csharp(text: &str) -> String {
    let mut sources = SourceMap::new();
    let mut diags = Diagnostics::new();
    let file = sources.add("t.nb", text);
    let ast = nanobuf_syntax::parse(file, text, &mut diags).unwrap();
    let schema = nanobuf_schema::analyze(&[Unit { file, ast }], &mut diags)
        .unwrap_or_else(|| panic!("{}", diags.render(&sources, false)));
    let files = nanobuf_codegen::generate(&schema, nanobuf_codegen::Lang::CSharp, "out").unwrap();
    assert_eq!(files.len(), 1);
    assert_eq!(files[0].name, "out.cs");
    files[0].content.clone()
}

#[test]
fn output_is_deterministic() {
    let text = "schema a\nmessage M {\n  x: u32 @1\n  s: string @2\n}\n";
    assert_eq!(generate_csharp(text), generate_csharp(text));
}

#[test]
fn generates_expected_api_surface() {
    let code = generate_csharp(
        "schema demo.telemetry\nenum Status: u8 {\n  unknown = 0\n  ok = 1\n}\nmessage Packet {\n  status: Status @1\n  name: string @2\n  maybe: f64? @3\n}\n",
    );
    for expected in [
        "namespace Demo.Telemetry {",
        "public readonly struct Status : IEquatable<Status> {",
        "public readonly byte Value;",
        "public static readonly Status Ok = new(1);",
        "public string? Name() => Value switch {",
        "public sealed class Packet : IEquatable<Packet?> {",
        "public Status Status { get; set; }",
        "public string Name { get; set; } = \"\";",
        "public double? Maybe { get; set; }",
        "public byte[] Encode() {",
        "public static Packet Decode(ReadOnlySpan<byte> data) => PacketView.Parse(data).ToOwned();",
        "public byte[] EncodeProto3() {",
        "public static Packet DecodeProto3(ReadOnlySpan<byte> data) {",
        "public readonly ref struct PacketView {",
        "public static PacketView Parse(ReadOnlySpan<byte> data) => new(data, global::Nanobuf.Wire.ParseHeader(data));",
        "public ReadOnlySpan<byte> Data => _data;",
        "public Packet ToOwned() {",
    ] {
        assert!(code.contains(expected), "missing `{expected}` in:\n{code}");
    }
}

#[test]
fn header_marks_generated_output() {
    let code = generate_csharp("schema a\nmessage M {\n  x: u32 @1\n}\n");
    assert!(code.starts_with("// @generated by nanoc. DO NOT EDIT."));
    assert!(code.contains("#nullable enable"));
}

#[test]
fn doc_comments_are_carried_through() {
    let code = generate_csharp(
        "schema a\n/// The packet.\nmessage Packet {\n  /// Field doc.\n  x: u32 @1\n}\n",
    );
    assert!(code.contains("/// The packet."));
    assert!(code.contains("/// Field doc."));
}

#[test]
fn cross_package_references_are_fully_qualified() {
    let code = generate_csharp(
        "schema demo.telemetry\nmessage Header {\n  source: u32 @1\n}\nmessage Packet {\n  header: Header @1\n}\n",
    );
    // Same package: plain name.
    assert!(
        code.contains("public Header? Header { get; set; }"),
        "{code}"
    );
}

#[test]
fn keyword_field_names_are_pascal_cased() {
    // C# keywords are all lowercase, so PascalCase conversion already
    // avoids them; `event` becomes `Event`.
    let code = generate_csharp("schema a\nmessage M {\n  event: u32 @1\n  string: bool @2\n}\n");
    assert!(code.contains("public uint Event { get; set; }"), "{code}");
    assert!(code.contains("public bool String { get; set; }"), "{code}");
}

#[test]
fn reserved_view_member_names_get_prefixed() {
    let code = generate_csharp("schema a\nmessage M {\n  data: bytes @1\n  parse: u32 @2\n}\n");
    assert!(
        code.contains("public ReadOnlySpan<byte> GetData =>"),
        "{code}"
    );
    assert!(code.contains("public uint GetParse =>"), "{code}");
    // The owned class keeps the plain property names.
    assert!(
        code.contains("public byte[] Data { get; set; } = Array.Empty<byte>();"),
        "{code}"
    );
    assert!(code.contains("public uint Parse { get; set; }"), "{code}");
}

#[test]
fn recursive_message_fields_are_nullable_references() {
    let code = generate_csharp("schema a\nmessage Tree {\n  left: Tree @1\n}\n");
    assert!(code.contains("public Tree? Left { get; set; }"), "{code}");
    assert!(
        code.contains("public bool TryGetLeft(out TreeView value) {"),
        "{code}"
    );
}

#[test]
fn optional_fields_use_presence_bits() {
    let code = generate_csharp("schema a\nmessage M {\n  maybe: i16? @1\n}\n");
    assert!(code.contains("if (Maybe is { } maybeValue) {"), "{code}");
    assert!(code.contains("public short? Maybe =>"), "{code}");
}
