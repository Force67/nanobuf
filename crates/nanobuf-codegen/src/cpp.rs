//! C++ code generator. See `rust.rs` for the reference backend.
//!
//! Emits one C++17 header on top of the `nanobuf.h` runtime. Every message
//! gets an owned struct (`Packet`), a zero-copy view (`PacketView`), and
//! proto3 migration codecs. Structs are defined in dependency order and all
//! methods are defined out of line as `inline`, so recursive and
//! cross-package message references need no special casing.

use nanobuf_schema::{
    DataSlot, ElemType, Enum, EnumId, Field, Message, MessageId, ProtoEncoding, ScalarType, Schema,
    Type,
};

use crate::names::{cpp_ident, pascal};
use crate::writer::CodeWriter;

/// View methods that field accessors must not shadow.
const RESERVED_VIEW_METHODS: &[&str] = &["data", "size"];

pub fn generate(schema: &Schema) -> String {
    let mut w = CodeWriter::new("  ");
    w.line("// @generated by nanoc. DO NOT EDIT.");
    w.line("// Wire layout is fixed by the schema; see docs/wire-format.md.");
    w.line("//");
    w.line("// View accessors for heap fields distinguish corrupt buffers from");
    w.line("// absent fields:");
    w.line("//   - non-optional string/bytes accessors return std::optional<T>:");
    w.line("//     nullopt only on corruption, absent fields read as empty");
    w.line("//   - optional string/bytes accessors return nanobuf::Opt<T>: !ok()");
    w.line("//     means corrupt, an ok-but-empty result means absent");
    w.line("//   - message accessors return std::optional<View> and conflate the");
    w.line("//     two; ToOwned() reports corruption precisely");
    w.line("#pragma once");
    w.blank();
    w.line("#include <cstddef>");
    w.line("#include <cstdint>");
    w.line("#include <memory>");
    w.line("#include <optional>");
    w.line("#include <string>");
    w.line("#include <string_view>");
    w.line("#include <utility>");
    w.line("#include <vector>");
    w.blank();
    w.line("#include \"nanobuf.h\"");

    for package in schema.packages() {
        let ns = namespace_of(package);
        w.blank();
        w.line(format!("namespace {ns} {{"));
        w.blank();
        for m in schema.messages.iter().filter(|m| m.package == package) {
            let name = pascal(&m.name);
            w.line(format!("struct {name};"));
            w.line(format!("class {name}View;"));
        }
        w.blank();
        w.line(format!("}}  // namespace {ns}"));
    }

    for package in schema.packages() {
        let enums: Vec<_> = schema
            .enums
            .iter()
            .filter(|e| e.package == package)
            .collect();
        if enums.is_empty() {
            continue;
        }
        let ns = namespace_of(package);
        w.blank();
        w.line(format!("namespace {ns} {{"));
        for e in enums {
            w.blank();
            enum_def(&mut w, e);
        }
        w.blank();
        w.line(format!("}}  // namespace {ns}"));
    }

    // Struct and view definitions, dependency-ordered so that non-boxed
    // message-typed members are complete types.
    for (ns, ids) in package_runs(schema) {
        w.blank();
        w.line(format!("namespace {ns} {{"));
        for id in ids {
            let m = schema.message(id);
            w.blank();
            owned_struct(&mut w, schema, m);
            w.blank();
            equality(&mut w, m);
            w.blank();
            view_class(&mut w, schema, m);
        }
        w.blank();
        w.line(format!("}}  // namespace {ns}"));
    }

    for (ns, ids) in package_runs(schema) {
        w.blank();
        w.line(format!("namespace {ns} {{"));
        for id in ids {
            message_impl(&mut w, schema, schema.message(id));
        }
        w.blank();
        w.line(format!("}}  // namespace {ns}"));
    }

    w.finish()
}

/// C++ namespace for a package: `demo.telemetry` -> `demo::telemetry`.
fn namespace_of(package: &str) -> String {
    package
        .split('.')
        .map(cpp_ident)
        .collect::<Vec<_>>()
        .join("::")
}

/// Messages in definition order, grouped into runs of one namespace.
fn package_runs(schema: &Schema) -> Vec<(String, Vec<MessageId>)> {
    let mut runs: Vec<(String, Vec<MessageId>)> = Vec::new();
    for id in schema.message_order() {
        let ns = namespace_of(&schema.message(id).package);
        match runs.last_mut() {
            Some((last, ids)) if *last == ns => ids.push(id),
            _ => runs.push((ns, vec![id])),
        }
    }
    runs
}

fn cpp_scalar(s: ScalarType) -> &'static str {
    match s {
        ScalarType::Bool => "bool",
        ScalarType::U8 => "uint8_t",
        ScalarType::U16 => "uint16_t",
        ScalarType::U32 => "uint32_t",
        ScalarType::U64 => "uint64_t",
        ScalarType::I8 => "int8_t",
        ScalarType::I16 => "int16_t",
        ScalarType::I32 => "int32_t",
        ScalarType::I64 => "int64_t",
        ScalarType::F32 => "float",
        ScalarType::F64 => "double",
    }
}

/// Name of a message or enum type as seen from `current`'s namespace.
fn type_ref(current: &Message, package: &str, name: &str) -> String {
    let name = pascal(name);
    if package == current.package {
        name
    } else {
        format!("::{}::{name}", namespace_of(package))
    }
}

fn message_ref(schema: &Schema, current: &Message, id: MessageId) -> String {
    let target = schema.message(id);
    type_ref(current, &target.package, &target.name)
}

fn view_ref(schema: &Schema, current: &Message, id: MessageId) -> String {
    let target = schema.message(id);
    type_ref(
        current,
        &target.package,
        &format!("{}View", pascal(&target.name)),
    )
}

fn enum_ref(schema: &Schema, current: &Message, id: EnumId) -> String {
    let target = schema.enumeration(id);
    type_ref(current, &target.package, &target.name)
}

fn constant_name(variant: &str) -> String {
    format!("k{}", pascal(variant))
}

fn enum_def(w: &mut CodeWriter, e: &Enum) {
    let name = pascal(&e.name);
    let backing = cpp_scalar(e.backing);
    w.doc(&e.docs, "//");
    w.line("// Open enum: values outside the schema are preserved.");
    w.open(format!("struct {name} {{"));
    w.line(format!("{backing} value = 0;"));
    w.blank();
    w.line("// Schema name of the value, or nullptr if it has none.");
    w.open("const char* name() const {");
    w.open("switch (value) {");
    for v in &e.variants {
        w.line(format!("case {}: return \"{}\";", v.value, v.name));
    }
    w.line("default: return nullptr;");
    w.close("}");
    w.close("}");
    w.blank();
    for v in &e.variants {
        w.doc(&v.docs, "//");
        w.line(format!("static const {name} {};", constant_name(&v.name)));
    }
    w.close("};");
    w.blank();
    for v in &e.variants {
        w.line(format!(
            "inline constexpr {name} {name}::{}{{{}}};",
            constant_name(&v.name),
            v.value
        ));
    }
    w.blank();
    w.line(format!(
        "inline bool operator==({name} a, {name} b) {{ return a.value == b.value; }}"
    ));
    w.line(format!(
        "inline bool operator!=({name} a, {name} b) {{ return a.value != b.value; }}"
    ));
}

fn owned_type(schema: &Schema, m: &Message, f: &Field) -> String {
    let base = match f.ty {
        Type::Scalar(s) => cpp_scalar(s).to_string(),
        Type::Enum(id) => enum_ref(schema, m, id),
        Type::String => "std::string".to_string(),
        Type::Bytes => "std::vector<uint8_t>".to_string(),
        Type::Message(id) => {
            let path = message_ref(schema, m, id);
            return if f.boxed {
                format!("std::unique_ptr<{path}>")
            } else {
                format!("std::optional<{path}>")
            };
        }
        Type::List(elem) => {
            let elem = match elem {
                ElemType::Scalar(s) => cpp_scalar(s).to_string(),
                ElemType::Enum(id) => enum_ref(schema, m, id),
                ElemType::String => "std::string".to_string(),
                ElemType::Bytes => "std::vector<uint8_t>".to_string(),
                ElemType::Message(id) => message_ref(schema, m, id),
            };
            return format!("std::vector<{elem}>");
        }
    };
    if f.optional {
        format!("std::optional<{base}>")
    } else {
        base
    }
}

fn field_decl(schema: &Schema, m: &Message, f: &Field) -> String {
    let ty = owned_type(schema, m, f);
    let name = cpp_ident(&f.name);
    match f.ty {
        Type::Scalar(ScalarType::Bool) if !f.optional => format!("{ty} {name} = false;"),
        Type::Scalar(_) if !f.optional => format!("{ty} {name} = 0;"),
        _ => format!("{ty} {name};"),
    }
}

fn owned_struct(w: &mut CodeWriter, schema: &Schema, m: &Message) {
    let name = pascal(&m.name);
    w.doc(&m.docs, "//");
    w.open(format!("struct {name} {{"));
    for f in &m.fields {
        w.doc(&f.docs, "//");
        w.line(field_decl(schema, m, f));
    }
    if !m.fields.is_empty() {
        w.blank();
    }
    w.line(format!(
        "static constexpr uint16_t kFixedLen = {};",
        m.fixed_len
    ));
    w.blank();
    w.line("std::vector<uint8_t> Encode() const;");
    w.line(format!(
        "static std::optional<{name}> Decode(const uint8_t* data, size_t size);"
    ));
    w.line("std::vector<uint8_t> EncodeProto3() const;");
    w.line(format!(
        "static std::optional<{name}> DecodeProto3(const uint8_t* data, size_t size);"
    ));
    w.blank();
    w.line("// Internal: serializes into an in-progress message buffer.");
    w.line("void WriteTo(nanobuf::Writer& w) const;");
    w.line("// Internal: appends proto3-encoded fields to `out`.");
    w.line("void WriteProto3To(std::vector<uint8_t>& out) const;");
    w.close("};");
}

fn equality(w: &mut CodeWriter, m: &Message) {
    let name = pascal(&m.name);
    w.open(format!(
        "inline bool operator==(const {name}& a, const {name}& b) {{"
    ));
    if m.fields.is_empty() {
        w.line("static_cast<void>(a);");
        w.line("static_cast<void>(b);");
    }
    for f in &m.fields {
        let field = cpp_ident(&f.name);
        if f.boxed {
            // Boxed fields compare through the pointer.
            w.open(format!(
                "if (static_cast<bool>(a.{field}) != static_cast<bool>(b.{field})) {{"
            ));
            w.line("return false;");
            w.close("}");
            w.open(format!("if (a.{field} && !(*a.{field} == *b.{field})) {{"));
            w.line("return false;");
            w.close("}");
        } else {
            w.open(format!("if (!(a.{field} == b.{field})) {{"));
            w.line("return false;");
            w.close("}");
        }
    }
    w.line("return true;");
    w.close("}");
    w.blank();
    w.line(format!(
        "inline bool operator!=(const {name}& a, const {name}& b) {{ return !(a == b); }}"
    ));
}

/// Method name for a field accessor on the view, avoiding builtins.
fn accessor_name(f: &Field) -> String {
    let name = cpp_ident(&f.name);
    if RESERVED_VIEW_METHODS.contains(&name.as_str()) {
        format!("get_{name}")
    } else {
        name
    }
}

/// Return type of the view accessor for `f`.
fn accessor_type(schema: &Schema, m: &Message, f: &Field) -> String {
    match f.ty {
        Type::Scalar(s) => {
            let base = cpp_scalar(s);
            if f.optional {
                format!("std::optional<{base}>")
            } else {
                base.to_string()
            }
        }
        Type::Enum(id) => {
            let base = enum_ref(schema, m, id);
            if f.optional {
                format!("std::optional<{base}>")
            } else {
                base
            }
        }
        Type::String => {
            if f.optional {
                "nanobuf::Opt<std::string_view>".to_string()
            } else {
                "std::optional<std::string_view>".to_string()
            }
        }
        Type::Bytes => {
            if f.optional {
                "nanobuf::Opt<nanobuf::BytesView>".to_string()
            } else {
                "std::optional<nanobuf::BytesView>".to_string()
            }
        }
        Type::Message(id) => format!("std::optional<{}>", view_ref(schema, m, id)),
        Type::List(elem) => match elem {
            ElemType::Scalar(s) => {
                format!("std::optional<nanobuf::ScalarList<{}>>", cpp_scalar(s))
            }
            ElemType::Enum(id) => format!(
                "std::optional<nanobuf::ScalarList<{}>>",
                enum_ref(schema, m, id)
            ),
            ElemType::String => "std::optional<nanobuf::StrList>".to_string(),
            ElemType::Bytes => "std::optional<nanobuf::BytesList>".to_string(),
            ElemType::Message(id) => format!(
                "std::optional<nanobuf::MessageList<{}>>",
                view_ref(schema, m, id)
            ),
        },
    }
}

fn view_class(w: &mut CodeWriter, schema: &Schema, m: &Message) {
    let name = pascal(&m.name);
    let view = format!("{name}View");
    w.line(format!("// Zero-copy reader for {name}."));
    w.line(format!("class {view} {{"));
    w.line(" public:");
    w.line(format!(
        "  static std::optional<{view}> Parse(const uint8_t* data, size_t size);"
    ));
    w.blank();
    w.line("  // Internal: wraps an already validated message view.");
    w.line(format!(
        "  explicit {view}(nanobuf::View view) : view_(view) {{}}"
    ));
    w.blank();
    w.line("  // Raw message bytes, for forwarding without re-encoding.");
    w.line("  const uint8_t* data() const { return view_.data(); }");
    w.line("  size_t size() const { return view_.size(); }");
    w.blank();
    for f in &m.fields {
        for doc in &f.docs {
            w.line(format!("  // {doc}"));
        }
        w.line(format!(
            "  {} {}() const;",
            accessor_type(schema, m, f),
            accessor_name(f)
        ));
    }
    w.blank();
    w.line(format!("  // Copies every field into an owned {name}."));
    w.line(format!("  std::optional<{name}> ToOwned() const;"));
    w.blank();
    w.line(" private:");
    w.line("  nanobuf::View view_;");
    w.line("};");
}

fn message_impl(w: &mut CodeWriter, schema: &Schema, m: &Message) {
    let name = pascal(&m.name);
    let view = format!("{name}View");

    w.blank();
    w.open(format!(
        "inline std::vector<uint8_t> {name}::Encode() const {{"
    ));
    w.line("nanobuf::Writer w;");
    w.line("WriteTo(w);");
    w.line("return w.TakeBuffer();");
    w.close("}");

    w.blank();
    w.open(format!(
        "inline std::optional<{name}> {name}::Decode(const uint8_t* data, size_t size) {{"
    ));
    w.line(format!(
        "std::optional<{view}> view = {view}::Parse(data, size);"
    ));
    w.open("if (!view.has_value()) {");
    w.line("return std::nullopt;");
    w.close("}");
    w.line("return view->ToOwned();");
    w.close("}");

    w.blank();
    w.open(format!(
        "inline void {name}::WriteTo(nanobuf::Writer& w) const {{"
    ));
    w.line("w.Begin(kFixedLen);");
    for f in &m.fields {
        write_field(w, schema, m, f);
    }
    w.close("}");

    proto_codecs(w, schema, m, &name);

    w.blank();
    w.open(format!(
        "inline std::optional<{view}> {view}::Parse(const uint8_t* data, size_t size) {{"
    ));
    w.line("std::optional<nanobuf::View> view = nanobuf::View::Parse(data, size);");
    w.open("if (!view.has_value()) {");
    w.line("return std::nullopt;");
    w.close("}");
    w.line(format!("return {view}(*view);"));
    w.close("}");

    for f in &m.fields {
        w.blank();
        view_accessor(w, schema, m, f);
    }

    w.blank();
    to_owned(w, schema, m, &name, &view);
}

/// Emits the `WriteTo` statements for one field.
fn write_field(w: &mut CodeWriter, schema: &Schema, m: &Message, f: &Field) {
    let field = format!("this->{}", cpp_ident(&f.name));
    match (f.layout.data, f.ty) {
        (DataSlot::Bit(bit), _) => {
            if let Some(p) = f.layout.presence {
                w.open(format!("if ({field}.has_value()) {{"));
                w.line(format!("w.PutBit({}, {}, true);", p.byte, p.bit));
                w.line(format!("w.PutBit({}, {}, *{field});", bit.byte, bit.bit));
                w.close("}");
            } else {
                w.line(format!("w.PutBit({}, {}, {field});", bit.byte, bit.bit));
            }
        }
        (DataSlot::Bytes { offset, .. }, _) => {
            if let Some(p) = f.layout.presence {
                w.open(format!("if ({field}.has_value()) {{"));
                w.line(format!("w.PutBit({}, {}, true);", p.byte, p.bit));
                w.line(format!("w.PutScalar({offset}, *{field});"));
                w.close("}");
            } else {
                w.line(format!("w.PutScalar({offset}, {field});"));
            }
        }
        (DataSlot::Offset { offset }, Type::String) => {
            if f.optional {
                w.open(format!("if ({field}.has_value()) {{"));
                w.line(format!("w.PutString({offset}, *{field}, true);"));
                w.close("}");
            } else {
                w.line(format!("w.PutString({offset}, {field}, false);"));
            }
        }
        (DataSlot::Offset { offset }, Type::Bytes) => {
            if f.optional {
                w.open(format!("if ({field}.has_value()) {{"));
                w.line(format!("w.PutBytes({offset}, *{field}, true);"));
                w.close("}");
            } else {
                w.line(format!("w.PutBytes({offset}, {field}, false);"));
            }
        }
        (DataSlot::Offset { offset }, Type::Message(_)) => {
            let present = if f.boxed {
                format!("{field} != nullptr")
            } else {
                format!("{field}.has_value()")
            };
            w.open(format!("if ({present}) {{"));
            w.open(format!(
                "w.PutMessage({offset}, [&](nanobuf::Writer& inner) {{"
            ));
            w.line(format!("{field}->WriteTo(inner);"));
            w.close("});");
            w.close("}");
        }
        (DataSlot::Offset { offset }, Type::List(elem)) => match elem {
            ElemType::Scalar(_) | ElemType::Enum(_) => {
                w.line(format!("w.PutScalarList({offset}, {field});"));
            }
            ElemType::String => {
                w.open(format!(
                    "w.PutOffsetList({offset}, {field}, [](nanobuf::Writer& inner, const std::string& item) {{"
                ));
                w.line("return inner.HeapString(item);");
                w.close("});");
            }
            ElemType::Bytes => {
                w.open(format!(
                    "w.PutOffsetList({offset}, {field}, [](nanobuf::Writer& inner, const std::vector<uint8_t>& item) {{"
                ));
                w.line("return inner.HeapBytes(item);");
                w.close("});");
            }
            ElemType::Message(id) => {
                let path = message_ref(schema, m, id);
                w.open(format!(
                    "w.PutOffsetList({offset}, {field}, [](nanobuf::Writer& inner, const {path}& item) {{"
                ));
                w.open("return inner.HeapMessage([&item](nanobuf::Writer& nested) {");
                w.line("item.WriteTo(nested);");
                w.close("});");
                w.close("});");
            }
        },
        (slot, ty) => unreachable!("invalid slot {slot:?} for type {ty:?}"),
    }
}

fn view_accessor(w: &mut CodeWriter, schema: &Schema, m: &Message, f: &Field) {
    let view = format!("{}View", pascal(&m.name));
    let method = accessor_name(f);
    let ret = accessor_type(schema, m, f);
    w.open(format!("inline {ret} {view}::{method}() const {{"));
    match (f.layout.data, f.ty) {
        (DataSlot::Bit(bit), _) => {
            if let Some(p) = f.layout.presence {
                w.open(format!("if (!view_.BitAt({}, {})) {{", p.byte, p.bit));
                w.line("return std::nullopt;");
                w.close("}");
            }
            w.line(format!("return view_.BitAt({}, {});", bit.byte, bit.bit));
        }
        (DataSlot::Bytes { offset, .. }, ty) => {
            let value_type = match ty {
                Type::Scalar(s) => cpp_scalar(s).to_string(),
                Type::Enum(id) => enum_ref(schema, m, id),
                _ => unreachable!("byte slots hold scalars and enums"),
            };
            if let Some(p) = f.layout.presence {
                w.open(format!("if (!view_.BitAt({}, {})) {{", p.byte, p.bit));
                w.line("return std::nullopt;");
                w.close("}");
            }
            w.line(format!("return view_.ScalarAt<{value_type}>({offset});"));
        }
        (DataSlot::Offset { offset }, Type::String) => {
            if f.optional {
                w.line(format!("return view_.StrAt({offset});"));
            } else {
                w.line(format!(
                    "nanobuf::Opt<std::string_view> value = view_.StrAt({offset});"
                ));
                w.open("if (!value.ok()) {");
                w.line("return std::nullopt;");
                w.close("}");
                w.line("return value.has_value() ? value.value() : std::string_view();");
            }
        }
        (DataSlot::Offset { offset }, Type::Bytes) => {
            if f.optional {
                w.line(format!("return view_.BytesAt({offset});"));
            } else {
                w.line(format!(
                    "nanobuf::Opt<nanobuf::BytesView> value = view_.BytesAt({offset});"
                ));
                w.open("if (!value.ok()) {");
                w.line("return std::nullopt;");
                w.close("}");
                w.line("return value.has_value() ? value.value() : nanobuf::BytesView();");
            }
        }
        (DataSlot::Offset { offset }, Type::Message(id)) => {
            let child = view_ref(schema, m, id);
            w.line(format!(
                "nanobuf::Opt<nanobuf::View> value = view_.MessageAt({offset});"
            ));
            w.open("if (!value.ok() || !value.has_value()) {");
            w.line("return std::nullopt;");
            w.close("}");
            w.line(format!("return {child}(value.value());"));
        }
        (DataSlot::Offset { offset }, Type::List(elem)) => match elem {
            ElemType::Scalar(s) => {
                w.line(format!(
                    "return view_.ScalarListAt<{}>({offset});",
                    cpp_scalar(s)
                ));
            }
            ElemType::Enum(id) => {
                w.line(format!(
                    "return view_.ScalarListAt<{}>({offset});",
                    enum_ref(schema, m, id)
                ));
            }
            ElemType::String => {
                w.line(format!("return view_.StrListAt({offset});"));
            }
            ElemType::Bytes => {
                w.line(format!("return view_.BytesListAt({offset});"));
            }
            ElemType::Message(id) => {
                let child = view_ref(schema, m, id);
                w.line(format!(
                    "std::optional<nanobuf::OffsetList> list = view_.OffsetListAt({offset});"
                ));
                w.open("if (!list.has_value()) {");
                w.line("return std::nullopt;");
                w.close("}");
                w.line(format!("return nanobuf::MessageList<{child}>(*list);"));
            }
        },
        (slot, ty) => unreachable!("invalid slot {slot:?} for type {ty:?}"),
    }
    w.close("}");
}

fn to_owned(w: &mut CodeWriter, schema: &Schema, m: &Message, name: &str, view: &str) {
    w.open(format!(
        "inline std::optional<{name}> {view}::ToOwned() const {{"
    ));
    w.line(format!("{name} out;"));
    for f in &m.fields {
        let field = cpp_ident(&f.name);
        let method = accessor_name(f);
        match f.ty {
            Type::Scalar(_) | Type::Enum(_) => {
                w.line(format!("out.{field} = this->{method}();"));
            }
            Type::String => {
                w.open("{");
                if f.optional {
                    w.line(format!(
                        "nanobuf::Opt<std::string_view> value = this->{method}();"
                    ));
                    w.open("if (!value.ok()) {");
                    w.line("return std::nullopt;");
                    w.close("}");
                    w.open("if (value.has_value()) {");
                    w.line(format!("out.{field} = std::string(value.value());"));
                    w.close("}");
                } else {
                    w.line(format!(
                        "std::optional<std::string_view> value = this->{method}();"
                    ));
                    w.open("if (!value.has_value()) {");
                    w.line("return std::nullopt;");
                    w.close("}");
                    w.line(format!("out.{field} = std::string(*value);"));
                }
                w.close("}");
            }
            Type::Bytes => {
                w.open("{");
                if f.optional {
                    w.line(format!(
                        "nanobuf::Opt<nanobuf::BytesView> value = this->{method}();"
                    ));
                    w.open("if (!value.ok()) {");
                    w.line("return std::nullopt;");
                    w.close("}");
                    w.open("if (value.has_value()) {");
                    w.line(format!("out.{field} = value.value().ToVector();"));
                    w.close("}");
                } else {
                    w.line(format!(
                        "std::optional<nanobuf::BytesView> value = this->{method}();"
                    ));
                    w.open("if (!value.has_value()) {");
                    w.line("return std::nullopt;");
                    w.close("}");
                    w.line(format!("out.{field} = value->ToVector();"));
                }
                w.close("}");
            }
            Type::Message(id) => {
                let child_type = message_ref(schema, m, id);
                let child_view = view_ref(schema, m, id);
                let slot = match f.layout.data {
                    DataSlot::Offset { offset } => offset,
                    _ => unreachable!("message fields use offset slots"),
                };
                w.open("{");
                // Goes through the raw view to distinguish an absent field
                // from a corrupt buffer.
                w.line(format!(
                    "nanobuf::Opt<nanobuf::View> value = view_.MessageAt({slot});"
                ));
                w.open("if (!value.ok()) {");
                w.line("return std::nullopt;");
                w.close("}");
                w.open("if (value.has_value()) {");
                w.line(format!(
                    "std::optional<{child_type}> child = {child_view}(value.value()).ToOwned();"
                ));
                w.open("if (!child.has_value()) {");
                w.line("return std::nullopt;");
                w.close("}");
                if f.boxed {
                    w.line(format!(
                        "out.{field} = std::make_unique<{child_type}>(std::move(*child));"
                    ));
                } else {
                    w.line(format!("out.{field} = std::move(*child);"));
                }
                w.close("}");
                w.close("}");
            }
            Type::List(elem) => {
                w.open("{");
                w.line(format!("auto value = this->{method}();"));
                w.open("if (!value.has_value()) {");
                w.line("return std::nullopt;");
                w.close("}");
                match elem {
                    ElemType::Scalar(_) | ElemType::Enum(_) => {
                        w.line(format!("out.{field} = value->ToVector();"));
                    }
                    ElemType::String | ElemType::Bytes => {
                        w.line("auto items = value->ToVector();");
                        w.open("if (!items.has_value()) {");
                        w.line("return std::nullopt;");
                        w.close("}");
                        w.line(format!("out.{field} = std::move(*items);"));
                    }
                    ElemType::Message(id) => {
                        let child_type = message_ref(schema, m, id);
                        let child_view = view_ref(schema, m, id);
                        w.open("for (size_t i = 0; i < value->size(); ++i) {");
                        w.line(format!("std::optional<{child_view}> item = value->Get(i);"));
                        w.open("if (!item.has_value()) {");
                        w.line("return std::nullopt;");
                        w.close("}");
                        w.line(format!(
                            "std::optional<{child_type}> child = item->ToOwned();"
                        ));
                        w.open("if (!child.has_value()) {");
                        w.line("return std::nullopt;");
                        w.close("}");
                        w.line(format!("out.{field}.push_back(std::move(*child));"));
                        w.close("}");
                    }
                }
                w.close("}");
            }
        }
    }
    w.line("return out;");
    w.close("}");
}

/// Proto3 migration codecs.
fn proto_codecs(w: &mut CodeWriter, schema: &Schema, m: &Message, name: &str) {
    w.blank();
    w.open(format!(
        "inline std::vector<uint8_t> {name}::EncodeProto3() const {{"
    ));
    w.line("std::vector<uint8_t> out;");
    w.line("WriteProto3To(out);");
    w.line("return out;");
    w.close("}");

    w.blank();
    w.open(format!(
        "inline void {name}::WriteProto3To(std::vector<uint8_t>& out) const {{"
    ));
    if m.fields.is_empty() {
        w.line("static_cast<void>(out);");
    }
    for f in &m.fields {
        proto_write_field(w, f);
    }
    w.close("}");

    w.blank();
    w.open(format!(
        "inline std::optional<{name}> {name}::DecodeProto3(const uint8_t* data, size_t size) {{"
    ));
    w.line(format!("{name} message;"));
    w.line("nanobuf::proto::FieldReader reader(data, size);");
    w.line("uint32_t field = 0;");
    w.line("nanobuf::proto::WireValue value;");
    w.open("while (true) {");
    w.line("nanobuf::proto::FieldReader::Status status = reader.Next(&field, &value);");
    w.open("if (status == nanobuf::proto::FieldReader::Status::kDone) {");
    w.line("break;");
    w.close("}");
    w.open("if (status == nanobuf::proto::FieldReader::Status::kError) {");
    w.line("return std::nullopt;");
    w.close("}");
    w.open("switch (field) {");
    for f in &m.fields {
        proto_read_field(w, schema, m, f);
    }
    w.line("default:");
    w.line("  break;  // unknown field, skipped");
    w.close("}");
    w.close("}");
    w.line("return message;");
    w.close("}");
}

/// Expression converting `value` of the field's C++ type to the u64/u32 the
/// wire writer takes.
fn proto_scalar_encode(s: ScalarType, enc: ProtoEncoding, value: &str) -> String {
    match (enc, s) {
        (_, ScalarType::Bool) => format!("static_cast<uint64_t>({value})"),
        (ProtoEncoding::Fixed, ScalarType::F32) | (ProtoEncoding::Fixed, ScalarType::F64) => {
            format!("nanobuf::BitsOf({value})")
        }
        (ProtoEncoding::Fixed, s) if s.size() == 4 => format!("static_cast<uint32_t>({value})"),
        (ProtoEncoding::Fixed, _) => format!("static_cast<uint64_t>({value})"),
        (ProtoEncoding::ZigZag, _) => format!("nanobuf::proto::ZigZagEncode({value})"),
        // Signed varints sign-extend through int64_t.
        (ProtoEncoding::Varint, s) if s.is_signed() => {
            format!("static_cast<uint64_t>(static_cast<int64_t>({value}))")
        }
        (ProtoEncoding::Varint, _) => format!("static_cast<uint64_t>({value})"),
        (ProtoEncoding::LengthDelimited, _) => unreachable!("scalars are never length-delimited"),
    }
}

/// Expression converting the raw wire scalar `v` into the field's C++ type.
fn proto_scalar_decode(s: ScalarType, enc: ProtoEncoding, v: &str) -> String {
    match (enc, s) {
        (_, ScalarType::Bool) => format!("{v} != 0"),
        (ProtoEncoding::Fixed, ScalarType::F32) => format!("nanobuf::FloatFromBits({v})"),
        (ProtoEncoding::Fixed, ScalarType::F64) => format!("nanobuf::DoubleFromBits({v})"),
        (ProtoEncoding::ZigZag, _) => format!(
            "static_cast<{}>(nanobuf::proto::ZigZagDecode({v}))",
            cpp_scalar(s)
        ),
        _ => format!("static_cast<{}>({v})", cpp_scalar(s)),
    }
}

fn proto_write_field(w: &mut CodeWriter, f: &Field) {
    let field = format!("this->{}", cpp_ident(&f.name));
    let id = f.id;
    let tag_writer = |s: ScalarType, enc: ProtoEncoding, value: &str| -> String {
        match (enc, s.size()) {
            (ProtoEncoding::Fixed, 4) => format!(
                "nanobuf::proto::WriteI32Field(out, {id}, {});",
                proto_scalar_encode(s, enc, value)
            ),
            (ProtoEncoding::Fixed, _) => format!(
                "nanobuf::proto::WriteI64Field(out, {id}, {});",
                proto_scalar_encode(s, enc, value)
            ),
            _ => format!(
                "nanobuf::proto::WriteVarintField(out, {id}, {});",
                proto_scalar_encode(s, enc, value)
            ),
        }
    };
    match f.ty {
        Type::Scalar(s) => {
            if f.optional {
                w.open(format!("if ({field}.has_value()) {{"));
                w.line(tag_writer(s, f.proto, &format!("*{field}")));
                w.close("}");
            } else {
                let condition = if s == ScalarType::Bool {
                    format!("if ({field}) {{")
                } else {
                    format!("if ({field} != 0) {{")
                };
                w.open(condition);
                w.line(tag_writer(s, f.proto, &field));
                w.close("}");
            }
        }
        Type::Enum(_) => {
            let (cond, value) = if f.optional {
                (
                    format!("if ({field}.has_value()) {{"),
                    format!("{field}->value"),
                )
            } else {
                (
                    format!("if ({field}.value != 0) {{"),
                    format!("{field}.value"),
                )
            };
            w.open(cond);
            w.line(format!(
                "nanobuf::proto::WriteVarintField(out, {id}, static_cast<uint64_t>(static_cast<int64_t>({value})));"
            ));
            w.close("}");
        }
        Type::String | Type::Bytes => {
            let (cond, value) = if f.optional {
                (format!("if ({field}.has_value()) {{"), format!("*{field}"))
            } else {
                (format!("if (!{field}.empty()) {{"), field.clone())
            };
            w.open(cond);
            w.line(format!(
                "nanobuf::proto::WriteLenField(out, {id}, {value});"
            ));
            w.close("}");
        }
        Type::Message(_) => {
            let present = if f.boxed {
                format!("{field} != nullptr")
            } else {
                format!("{field}.has_value()")
            };
            w.open(format!("if ({present}) {{"));
            w.open(format!(
                "nanobuf::proto::WriteLenFieldWith(out, {id}, [&](std::vector<uint8_t>& nested) {{"
            ));
            w.line(format!("{field}->WriteProto3To(nested);"));
            w.close("});");
            w.close("}");
        }
        Type::List(elem) => {
            w.open(format!("if (!{field}.empty()) {{"));
            match elem {
                ElemType::Scalar(s) => {
                    let item = proto_scalar_encode(s, f.proto, &format!("{field}[i]"));
                    let append = match (f.proto, s.size()) {
                        (ProtoEncoding::Fixed, 4) => {
                            format!("nanobuf::proto::WriteFixed32(payload, {item});")
                        }
                        (ProtoEncoding::Fixed, _) => {
                            format!("nanobuf::proto::WriteFixed64(payload, {item});")
                        }
                        _ => format!("nanobuf::proto::WriteVarint(payload, {item});"),
                    };
                    w.open(format!(
                        "nanobuf::proto::WriteLenFieldWith(out, {id}, [&](std::vector<uint8_t>& payload) {{"
                    ));
                    w.open(format!("for (size_t i = 0; i < {field}.size(); ++i) {{"));
                    w.line(append);
                    w.close("}");
                    w.close("});");
                }
                ElemType::Enum(_) => {
                    w.open(format!(
                        "nanobuf::proto::WriteLenFieldWith(out, {id}, [&](std::vector<uint8_t>& payload) {{"
                    ));
                    w.open(format!("for (size_t i = 0; i < {field}.size(); ++i) {{"));
                    w.line(format!(
                        "nanobuf::proto::WriteVarint(payload, static_cast<uint64_t>(static_cast<int64_t>({field}[i].value)));"
                    ));
                    w.close("}");
                    w.close("});");
                }
                ElemType::String | ElemType::Bytes => {
                    w.open(format!("for (size_t i = 0; i < {field}.size(); ++i) {{"));
                    w.line(format!(
                        "nanobuf::proto::WriteLenField(out, {id}, {field}[i]);"
                    ));
                    w.close("}");
                }
                ElemType::Message(_) => {
                    w.open(format!("for (size_t i = 0; i < {field}.size(); ++i) {{"));
                    w.open(format!(
                        "nanobuf::proto::WriteLenFieldWith(out, {id}, [&](std::vector<uint8_t>& nested) {{"
                    ));
                    w.line(format!("{field}[i].WriteProto3To(nested);"));
                    w.close("});");
                    w.close("}");
                }
            }
            w.close("}");
        }
    }
}

fn proto_read_field(w: &mut CodeWriter, schema: &Schema, m: &Message, f: &Field) {
    let field = cpp_ident(&f.name);
    let id = f.id;
    match f.ty {
        Type::Scalar(s) => {
            let (raw_type, expect) = match (f.proto, s.size()) {
                (ProtoEncoding::Fixed, 4) => ("uint32_t", "ExpectI32"),
                (ProtoEncoding::Fixed, _) => ("uint64_t", "ExpectI64"),
                _ => ("uint64_t", "ExpectVarint"),
            };
            w.open(format!("case {id}: {{"));
            w.line(format!("{raw_type} raw;"));
            w.open(format!("if (!nanobuf::proto::{expect}(value, &raw)) {{"));
            w.line("return std::nullopt;");
            w.close("}");
            w.line(format!(
                "message.{field} = {};",
                proto_scalar_decode(s, f.proto, "raw")
            ));
            w.line("break;");
            w.close("}");
        }
        Type::Enum(target) => {
            let path = enum_ref(schema, m, target);
            let backing = cpp_scalar(schema.enumeration(target).backing);
            w.open(format!("case {id}: {{"));
            w.line("uint64_t raw;");
            w.open("if (!nanobuf::proto::ExpectVarint(value, &raw)) {");
            w.line("return std::nullopt;");
            w.close("}");
            w.line(format!(
                "message.{field} = {path}{{static_cast<{backing}>(raw)}};"
            ));
            w.line("break;");
            w.close("}");
        }
        Type::String => {
            w.open(format!("case {id}: {{"));
            w.line("std::string item;");
            w.open("if (!nanobuf::proto::ExpectString(value, &item)) {");
            w.line("return std::nullopt;");
            w.close("}");
            w.line(format!("message.{field} = std::move(item);"));
            w.line("break;");
            w.close("}");
        }
        Type::Bytes => {
            w.open(format!("case {id}: {{"));
            w.line("std::vector<uint8_t> item;");
            w.open("if (!nanobuf::proto::ExpectBytes(value, &item)) {");
            w.line("return std::nullopt;");
            w.close("}");
            w.line(format!("message.{field} = std::move(item);"));
            w.line("break;");
            w.close("}");
        }
        Type::Message(target) => {
            let path = message_ref(schema, m, target);
            w.open(format!("case {id}: {{"));
            w.line("const uint8_t* payload;");
            w.line("size_t payload_size;");
            w.open("if (!nanobuf::proto::ExpectLen(value, &payload, &payload_size)) {");
            w.line("return std::nullopt;");
            w.close("}");
            w.line(format!(
                "std::optional<{path}> child = {path}::DecodeProto3(payload, payload_size);"
            ));
            w.open("if (!child.has_value()) {");
            w.line("return std::nullopt;");
            w.close("}");
            if f.boxed {
                w.line(format!(
                    "message.{field} = std::make_unique<{path}>(std::move(*child));"
                ));
            } else {
                w.line(format!("message.{field} = std::move(*child);"));
            }
            w.line("break;");
            w.close("}");
        }
        Type::List(elem) => match elem {
            ElemType::Scalar(s) => {
                let (reader, raw_type) = match (f.proto, s.size()) {
                    (ProtoEncoding::Fixed, 4) => ("ReadPackedFixed32", "uint32_t"),
                    (ProtoEncoding::Fixed, _) => ("ReadPackedFixed64", "uint64_t"),
                    _ => ("ReadPackedVarints", "uint64_t"),
                };
                let expr = proto_scalar_decode(s, f.proto, "v");
                w.open(format!("case {id}: {{"));
                w.open(format!(
                    "bool ok = nanobuf::proto::{reader}(value, [&message]({raw_type} v) {{"
                ));
                w.line(format!("message.{field}.push_back({expr});"));
                w.close("});");
                w.open("if (!ok) {");
                w.line("return std::nullopt;");
                w.close("}");
                w.line("break;");
                w.close("}");
            }
            ElemType::Enum(target) => {
                let path = enum_ref(schema, m, target);
                let backing = cpp_scalar(schema.enumeration(target).backing);
                w.open(format!("case {id}: {{"));
                w.open(
                    "bool ok = nanobuf::proto::ReadPackedVarints(value, [&message](uint64_t v) {",
                );
                w.line(format!(
                    "message.{field}.push_back({path}{{static_cast<{backing}>(v)}});"
                ));
                w.close("});");
                w.open("if (!ok) {");
                w.line("return std::nullopt;");
                w.close("}");
                w.line("break;");
                w.close("}");
            }
            ElemType::String => {
                w.open(format!("case {id}: {{"));
                w.line("std::string item;");
                w.open("if (!nanobuf::proto::ExpectString(value, &item)) {");
                w.line("return std::nullopt;");
                w.close("}");
                w.line(format!("message.{field}.push_back(std::move(item));"));
                w.line("break;");
                w.close("}");
            }
            ElemType::Bytes => {
                w.open(format!("case {id}: {{"));
                w.line("std::vector<uint8_t> item;");
                w.open("if (!nanobuf::proto::ExpectBytes(value, &item)) {");
                w.line("return std::nullopt;");
                w.close("}");
                w.line(format!("message.{field}.push_back(std::move(item));"));
                w.line("break;");
                w.close("}");
            }
            ElemType::Message(target) => {
                let path = message_ref(schema, m, target);
                w.open(format!("case {id}: {{"));
                w.line("const uint8_t* payload;");
                w.line("size_t payload_size;");
                w.open("if (!nanobuf::proto::ExpectLen(value, &payload, &payload_size)) {");
                w.line("return std::nullopt;");
                w.close("}");
                w.line(format!(
                    "std::optional<{path}> child = {path}::DecodeProto3(payload, payload_size);"
                ));
                w.open("if (!child.has_value()) {");
                w.line("return std::nullopt;");
                w.close("}");
                w.line(format!("message.{field}.push_back(std::move(*child));"));
                w.line("break;");
                w.close("}");
            }
        },
    }
}
