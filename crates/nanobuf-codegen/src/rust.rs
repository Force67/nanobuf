//! Rust code generator.
//!
//! Emits one file containing a module per package. Every message gets an
//! owned struct (`Packet`), a zero-copy view (`PacketView`), and proto3
//! migration codecs. All wire offsets come from the schema IR.

use nanobuf_schema::{
    DataSlot, ElemType, Enum, EnumId, Field, Message, MessageId, ProtoEncoding, ScalarType, Schema,
    Type,
};

use crate::names::{pascal, rust_ident, rust_module, shout};
use crate::writer::CodeWriter;

/// View methods that field accessors must not shadow.
const RESERVED_VIEW_METHODS: &[&str] = &["parse", "data", "to_owned", "from_view"];

pub fn generate(schema: &Schema) -> String {
    let mut w = CodeWriter::new("    ");
    w.line("// @generated by nanoc. DO NOT EDIT.");
    w.line("// Wire layout is fixed by the schema; see docs/wire-format.md.");
    for package in schema.packages() {
        w.blank();
        w.open(format!("pub mod {} {{", rust_module(package)));
        let mut first = true;
        for e in schema.enums.iter().filter(|e| e.package == package) {
            if !first {
                w.blank();
            }
            first = false;
            enum_def(&mut w, e);
        }
        for m in &schema.messages {
            if m.package != package {
                continue;
            }
            if !first {
                w.blank();
            }
            first = false;
            message_def(&mut w, schema, m);
        }
        w.close("}");
    }
    w.finish()
}

fn enum_def(w: &mut CodeWriter, e: &Enum) {
    let name = pascal(&e.name);
    let backing = rust_scalar(e.backing);
    w.doc(&e.docs, "///");
    w.line("/// Open enum: values outside the schema are preserved.");
    w.line("#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug, Default)]");
    w.line(format!("pub struct {name}(pub {backing});"));
    w.blank();
    w.open(format!("impl {name} {{"));
    for v in &e.variants {
        w.doc(&v.docs, "///");
        w.line(format!(
            "pub const {}: {name} = {name}({});",
            shout(&v.name),
            v.value
        ));
    }
    w.blank();
    w.line("/// Schema name of the value, if it has one.");
    w.open("pub fn name(self) -> Option<&'static str> {");
    w.open("match self.0 {");
    for v in &e.variants {
        w.line(format!("{} => Some(\"{}\"),", v.value, v.name));
    }
    w.line("_ => None,");
    w.close("}");
    w.close("}");
    w.close("}");
    w.blank();
    w.open(format!("impl nanobuf::Scalar for {name} {{"));
    w.line(format!("const SIZE: usize = {};", e.backing.size()));
    w.blank();
    w.open("fn read(bytes: &[u8]) -> Self {");
    w.line(format!(
        "{name}(<{backing} as nanobuf::Scalar>::read(bytes))"
    ));
    w.close("}");
    w.blank();
    w.open("fn store(self, bytes: &mut [u8]) {");
    w.line("nanobuf::Scalar::store(self.0, bytes);");
    w.close("}");
    w.blank();
    w.open("fn write(self, out: &mut Vec<u8>) {");
    w.line("nanobuf::Scalar::write(self.0, out);");
    w.close("}");
    w.close("}");
}

fn message_def(w: &mut CodeWriter, schema: &Schema, m: &Message) {
    let name = pascal(&m.name);
    let view_name = format!("{name}View");

    // Owned struct.
    w.doc(&m.docs, "///");
    w.line("#[derive(Clone, Debug, Default, PartialEq)]");
    w.open(format!("pub struct {name} {{"));
    for f in &m.fields {
        w.doc(&f.docs, "///");
        w.line(format!(
            "pub {}: {},",
            rust_ident(&f.name),
            owned_type(schema, m, f)
        ));
    }
    w.close("}");
    w.blank();

    w.open(format!("impl {name} {{"));
    w.line(format!("const FIXED_LEN: u16 = {};", m.fixed_len));
    w.blank();
    w.open("pub fn encode(&self) -> Vec<u8> {");
    w.line("let mut w = nanobuf::Writer::new();");
    w.line("self.write(&mut w);");
    w.line("w.into_vec()");
    w.close("}");
    w.blank();
    w.open(format!(
        "pub fn decode(data: &[u8]) -> Result<{name}, nanobuf::DecodeError> {{"
    ));
    w.line(format!("{view_name}::parse(data)?.to_owned()"));
    w.close("}");
    w.blank();
    w.open("pub(crate) fn write(&self, w: &mut nanobuf::Writer) {");
    w.line("w.begin(Self::FIXED_LEN);");
    for f in &m.fields {
        write_field(w, f);
    }
    w.close("}");
    proto_codecs(w, schema, m, &name);
    w.close("}");
    w.blank();

    // Zero-copy view.
    w.line(format!("/// Zero-copy reader for [`{name}`]."));
    w.line("#[derive(Clone, Copy, Debug)]");
    w.open(format!("pub struct {view_name}<'a> {{"));
    w.line("view: nanobuf::View<'a>,");
    w.close("}");
    w.blank();
    w.open(format!("impl<'a> {view_name}<'a> {{"));
    w.open("pub fn parse(data: &'a [u8]) -> Result<Self, nanobuf::DecodeError> {");
    w.line(format!(
        "Ok({view_name} {{ view: nanobuf::View::parse(data)? }})"
    ));
    w.close("}");
    w.blank();
    w.line("/// Raw message bytes, for forwarding without re-encoding.");
    w.open("pub fn data(&self) -> &'a [u8] {");
    w.line("self.view.data()");
    w.close("}");
    for f in &m.fields {
        w.blank();
        view_accessor(w, schema, m, f);
    }
    w.blank();
    to_owned(w, m, &name);
    w.close("}");
    w.blank();
    w.open(format!(
        "impl<'a> nanobuf::FromView<'a> for {view_name}<'a> {{"
    ));
    w.open("fn from_view(view: nanobuf::View<'a>) -> Self {");
    w.line(format!("{view_name} {{ view }}"));
    w.close("}");
    w.close("}");
}

/// Path to a message or enum type from inside `current`'s module.
fn type_path(current: &Message, package: &str, name: &str) -> String {
    let name = pascal(name);
    if package == current.package {
        name
    } else {
        format!("super::{}::{name}", rust_module(package))
    }
}

fn message_path(schema: &Schema, current: &Message, id: MessageId) -> String {
    let target = schema.message(id);
    type_path(current, &target.package, &target.name)
}

fn enum_path(schema: &Schema, current: &Message, id: EnumId) -> String {
    let target = schema.enumeration(id);
    type_path(current, &target.package, &target.name)
}

fn rust_scalar(s: ScalarType) -> &'static str {
    match s {
        // No stable `f16` primitive; the runtime carries the raw bits.
        ScalarType::F16 => "nanobuf::F16",
        _ => s.name(), // other scalar names are exactly the Rust primitives
    }
}

fn owned_type(schema: &Schema, m: &Message, f: &Field) -> String {
    let base = match f.ty {
        Type::Scalar(s) => rust_scalar(s).to_string(),
        Type::Enum(id) => enum_path(schema, m, id),
        Type::String => "String".to_string(),
        Type::Bytes => "Vec<u8>".to_string(),
        Type::Message(id) => {
            let path = message_path(schema, m, id);
            return if f.boxed {
                format!("Option<Box<{path}>>")
            } else {
                format!("Option<{path}>")
            };
        }
        Type::List(elem) => {
            let elem = match elem {
                ElemType::Scalar(s) => rust_scalar(s).to_string(),
                ElemType::Enum(id) => enum_path(schema, m, id),
                ElemType::String => "String".to_string(),
                ElemType::Bytes => "Vec<u8>".to_string(),
                ElemType::Message(id) => message_path(schema, m, id),
            };
            return format!("Vec<{elem}>");
        }
    };
    if f.optional {
        format!("Option<{base}>")
    } else {
        base
    }
}

/// Emits the `write` statements for one field.
fn write_field(w: &mut CodeWriter, f: &Field) {
    let field = rust_ident(&f.name);
    match (f.layout.data, f.ty) {
        (DataSlot::Bit(bit), _) => {
            if let Some(p) = f.layout.presence {
                w.open(format!("if let Some(value) = self.{field} {{"));
                w.line(format!("w.put_bit({}, {}, true);", p.byte, p.bit));
                w.line(format!("w.put_bit({}, {}, value);", bit.byte, bit.bit));
                w.close("}");
            } else {
                w.line(format!(
                    "w.put_bit({}, {}, self.{field});",
                    bit.byte, bit.bit
                ));
            }
        }
        (DataSlot::Bytes { offset, .. }, _) => {
            if let Some(p) = f.layout.presence {
                w.open(format!("if let Some(value) = self.{field} {{"));
                w.line(format!("w.put_bit({}, {}, true);", p.byte, p.bit));
                w.line(format!("w.put_scalar({offset}, value);"));
                w.close("}");
            } else {
                w.line(format!("w.put_scalar({offset}, self.{field});"));
            }
        }
        (DataSlot::Offset { offset }, Type::String) => {
            if f.optional {
                w.open(format!("if let Some(value) = &self.{field} {{"));
                w.line(format!("w.put_bytes({offset}, value.as_bytes(), true);"));
                w.close("}");
            } else {
                w.line(format!(
                    "w.put_bytes({offset}, self.{field}.as_bytes(), false);"
                ));
            }
        }
        (DataSlot::Offset { offset }, Type::Bytes) => {
            if f.optional {
                w.open(format!("if let Some(value) = &self.{field} {{"));
                w.line(format!("w.put_bytes({offset}, value, true);"));
                w.close("}");
            } else {
                w.line(format!("w.put_bytes({offset}, &self.{field}, false);"));
            }
        }
        (DataSlot::Offset { offset }, Type::Message(_)) => {
            w.open(format!("if let Some(value) = &self.{field} {{"));
            w.line(format!("w.put_message({offset}, |w| value.write(w));"));
            w.close("}");
        }
        (DataSlot::Offset { offset }, Type::List(elem)) => match elem {
            ElemType::Scalar(_) | ElemType::Enum(_) => {
                w.line(format!("w.put_scalar_list({offset}, &self.{field});"));
            }
            ElemType::String => {
                w.line(format!(
                    "w.put_offset_list({offset}, &self.{field}, |w, item| w.heap_bytes(item.as_bytes()));"
                ));
            }
            ElemType::Bytes => {
                w.line(format!(
                    "w.put_offset_list({offset}, &self.{field}, |w, item| w.heap_bytes(item));"
                ));
            }
            ElemType::Message(_) => {
                w.line(format!(
                    "w.put_offset_list({offset}, &self.{field}, |w, item| w.heap_message(|w| item.write(w)));"
                ));
            }
        },
        (slot, ty) => unreachable!("invalid slot {slot:?} for type {ty:?}"),
    }
}

/// Method name for a field accessor on the view, avoiding builtins.
fn accessor_name(f: &Field) -> String {
    let name = rust_ident(&f.name);
    if RESERVED_VIEW_METHODS.contains(&name.as_str()) {
        format!("get_{name}")
    } else {
        name
    }
}

fn view_accessor(w: &mut CodeWriter, schema: &Schema, m: &Message, f: &Field) {
    let method = accessor_name(f);
    w.doc(&f.docs, "///");
    match (f.layout.data, f.ty) {
        (DataSlot::Bit(bit), _) => {
            if let Some(p) = f.layout.presence {
                w.open(format!("pub fn {method}(&self) -> Option<bool> {{"));
                w.line(format!(
                    "self.view.bit_at({}, {}).then(|| self.view.bit_at({}, {}))",
                    p.byte, p.bit, bit.byte, bit.bit
                ));
                w.close("}");
            } else {
                w.open(format!("pub fn {method}(&self) -> bool {{"));
                w.line(format!("self.view.bit_at({}, {})", bit.byte, bit.bit));
                w.close("}");
            }
        }
        (DataSlot::Bytes { offset, .. }, ty) => {
            let value_type = match ty {
                Type::Scalar(s) => rust_scalar(s).to_string(),
                Type::Enum(id) => enum_path(schema, m, id),
                _ => unreachable!("byte slots hold scalars and enums"),
            };
            if let Some(p) = f.layout.presence {
                w.open(format!("pub fn {method}(&self) -> Option<{value_type}> {{"));
                w.line(format!(
                    "self.view.bit_at({}, {}).then(|| self.view.scalar_at({offset}))",
                    p.byte, p.bit
                ));
                w.close("}");
            } else {
                w.open(format!("pub fn {method}(&self) -> {value_type} {{"));
                w.line(format!("self.view.scalar_at({offset})"));
                w.close("}");
            }
        }
        (DataSlot::Offset { offset }, Type::String) => {
            if f.optional {
                w.open(format!(
                    "pub fn {method}(&self) -> Result<Option<&'a str>, nanobuf::DecodeError> {{"
                ));
                w.line(format!("self.view.str_at({offset})"));
            } else {
                w.open(format!(
                    "pub fn {method}(&self) -> Result<&'a str, nanobuf::DecodeError> {{"
                ));
                w.line(format!(
                    "Ok(self.view.str_at({offset})?.unwrap_or_default())"
                ));
            }
            w.close("}");
        }
        (DataSlot::Offset { offset }, Type::Bytes) => {
            if f.optional {
                w.open(format!(
                    "pub fn {method}(&self) -> Result<Option<&'a [u8]>, nanobuf::DecodeError> {{"
                ));
                w.line(format!("self.view.bytes_at({offset})"));
            } else {
                w.open(format!(
                    "pub fn {method}(&self) -> Result<&'a [u8], nanobuf::DecodeError> {{"
                ));
                w.line(format!(
                    "Ok(self.view.bytes_at({offset})?.unwrap_or_default())"
                ));
            }
            w.close("}");
        }
        (DataSlot::Offset { offset }, Type::Message(id)) => {
            let view = format!("{}View", message_path(schema, m, id));
            w.open(format!(
                "pub fn {method}(&self) -> Result<Option<{view}<'a>>, nanobuf::DecodeError> {{"
            ));
            w.line(format!(
                "Ok(self.view.message_at({offset})?.map(nanobuf::FromView::from_view))"
            ));
            w.close("}");
        }
        (DataSlot::Offset { offset }, Type::List(elem)) => match elem {
            ElemType::Scalar(s) => {
                let elem_ty = rust_scalar(s);
                w.open(format!(
                    "pub fn {method}(&self) -> Result<nanobuf::ScalarList<'a, {elem_ty}>, nanobuf::DecodeError> {{"
                ));
                w.line(format!("self.view.scalar_list_at({offset})"));
                w.close("}");
            }
            ElemType::Enum(id) => {
                let elem_ty = enum_path(schema, m, id);
                w.open(format!(
                    "pub fn {method}(&self) -> Result<nanobuf::ScalarList<'a, {elem_ty}>, nanobuf::DecodeError> {{"
                ));
                w.line(format!("self.view.scalar_list_at({offset})"));
                w.close("}");
            }
            ElemType::String => {
                w.open(format!(
                    "pub fn {method}(&self) -> Result<nanobuf::StrList<'a>, nanobuf::DecodeError> {{"
                ));
                w.line(format!(
                    "Ok(nanobuf::StrList(self.view.offset_list_at({offset})?))"
                ));
                w.close("}");
            }
            ElemType::Bytes => {
                w.open(format!(
                    "pub fn {method}(&self) -> Result<nanobuf::BytesList<'a>, nanobuf::DecodeError> {{"
                ));
                w.line(format!(
                    "Ok(nanobuf::BytesList(self.view.offset_list_at({offset})?))"
                ));
                w.close("}");
            }
            ElemType::Message(id) => {
                let view = format!("{}View", message_path(schema, m, id));
                w.open(format!(
                    "pub fn {method}(&self) -> Result<nanobuf::MessageList<'a, {view}<'a>>, nanobuf::DecodeError> {{"
                ));
                w.line(format!(
                    "Ok(nanobuf::MessageList::new(self.view.offset_list_at({offset})?))"
                ));
                w.close("}");
            }
        },
        (slot, ty) => unreachable!("invalid slot {slot:?} for type {ty:?}"),
    }
}

fn to_owned(w: &mut CodeWriter, m: &Message, name: &str) {
    w.line(format!("/// Copies every field into an owned [`{name}`]."));
    w.open(format!(
        "pub fn to_owned(&self) -> Result<{name}, nanobuf::DecodeError> {{"
    ));
    w.open(format!("Ok({name} {{"));
    for f in &m.fields {
        let field = rust_ident(&f.name);
        let method = accessor_name(f);
        let expr = match f.ty {
            Type::Scalar(_) | Type::Enum(_) => format!("self.{method}()"),
            Type::String => {
                if f.optional {
                    format!("self.{method}()?.map(str::to_string)")
                } else {
                    format!("self.{method}()?.to_string()")
                }
            }
            Type::Bytes => {
                if f.optional {
                    format!("self.{method}()?.map(<[u8]>::to_vec)")
                } else {
                    format!("self.{method}()?.to_vec()")
                }
            }
            Type::Message(_) => {
                let wrap = if f.boxed {
                    "Box::new(view.to_owned()?)"
                } else {
                    "view.to_owned()?"
                };
                format!("match self.{method}()? {{ Some(view) => Some({wrap}), None => None }}")
            }
            Type::List(elem) => match elem {
                ElemType::Scalar(_) | ElemType::Enum(_) => format!("self.{method}()?.to_vec()"),
                ElemType::String | ElemType::Bytes => format!("self.{method}()?.to_vec()?"),
                ElemType::Message(_) => format!(
                    "self.{method}()?.iter().map(|item| item?.to_owned()).collect::<Result<_, _>>()?"
                ),
            },
        };
        w.line(format!("{field}: {expr},"));
    }
    w.close("})");
    w.close("}");
}

/// Proto3 migration codecs on the owned type.
fn proto_codecs(w: &mut CodeWriter, schema: &Schema, m: &Message, name: &str) {
    w.blank();
    w.line("/// Encodes to the proto3 wire format (migration mode only).");
    w.open("pub fn encode_proto3(&self) -> Vec<u8> {");
    w.line("let mut out = Vec::new();");
    w.line("self.write_proto3(&mut out);");
    w.line("out");
    w.close("}");
    w.blank();
    w.open("pub(crate) fn write_proto3(&self, out: &mut Vec<u8>) {");
    if m.fields.is_empty() {
        w.line("let _ = out;");
    }
    for f in &m.fields {
        proto_write_field(w, f);
    }
    w.close("}");
    w.blank();
    w.line("/// Decodes the proto3 wire format (migration mode only).");
    w.open(format!(
        "pub fn decode_proto3(data: &[u8]) -> Result<{name}, nanobuf::DecodeError> {{"
    ));
    if m.fields.is_empty() {
        w.line("let mut reader = nanobuf::proto::FieldReader::new(data);");
        w.line("while reader.next()?.is_some() {}");
        w.line(format!("Ok({name}::default())"));
        w.close("}");
        return;
    }
    w.line(format!("let mut message = {name}::default();"));
    w.line("let mut reader = nanobuf::proto::FieldReader::new(data);");
    w.open("while let Some((field, value)) = reader.next()? {");
    w.line("#[allow(clippy::single_match)] // single-field messages keep the uniform shape");
    w.open("match field {");
    for f in &m.fields {
        proto_read_field(w, schema, m, f);
    }
    w.line("_ => {} // unknown field, skipped");
    w.close("}");
    w.close("}");
    w.line("Ok(message)");
    w.close("}");
}

/// Expression converting a scalar value `v: u64/u32` from the wire into
/// the field's Rust type, given the proto encoding.
fn proto_scalar_decode(s: ScalarType, enc: ProtoEncoding, v: &str) -> String {
    let ty = rust_scalar(s);
    match (enc, s) {
        (_, ScalarType::Bool) => format!("{v} != 0"),
        (ProtoEncoding::Fixed, ScalarType::F16) => {
            format!("nanobuf::F16::from_f32(f32::from_bits({v}))")
        }
        (ProtoEncoding::Fixed, ScalarType::F32) => format!("f32::from_bits({v})"),
        (ProtoEncoding::Fixed, ScalarType::F64) => format!("f64::from_bits({v})"),
        (ProtoEncoding::ZigZag, _) => format!("nanobuf::proto::zigzag_decode({v}) as {ty}"),
        _ => format!("{v} as {ty}"),
    }
}

/// Expression converting `value` of the field's Rust type to the u64/u32
/// the wire writer takes.
fn proto_scalar_encode(s: ScalarType, enc: ProtoEncoding, value: &str) -> String {
    match (enc, s) {
        (_, ScalarType::Bool) => format!("u64::from({value})"),
        // f16 travels widened to `float` on the proto3 wire.
        (ProtoEncoding::Fixed, ScalarType::F16) => format!("{value}.to_f32().to_bits()"),
        (ProtoEncoding::Fixed, ScalarType::F32) => format!("{value}.to_bits()"),
        (ProtoEncoding::Fixed, ScalarType::F64) => format!("{value}.to_bits()"),
        (ProtoEncoding::Fixed, s) if s.proto_size() == 4 => format!("{value} as u32"),
        (ProtoEncoding::Fixed, _) => format!("{value} as u64"),
        (ProtoEncoding::ZigZag, ScalarType::I64) => {
            format!("nanobuf::proto::zigzag_encode({value})")
        }
        (ProtoEncoding::ZigZag, _) => {
            format!("nanobuf::proto::zigzag_encode(i64::from({value}))")
        }
        (ProtoEncoding::Varint, ScalarType::I64) => format!("{value} as u64"),
        (ProtoEncoding::Varint, ScalarType::U64) => value.to_string(),
        (ProtoEncoding::Varint, s) if s.is_signed() => {
            format!("i64::from({value}) as u64")
        }
        (ProtoEncoding::Varint, _) => format!("u64::from({value})"),
        (ProtoEncoding::LengthDelimited, _) => unreachable!("scalars are never length-delimited"),
    }
}

/// Wire reader call yielding the raw scalar for the encoding: u64 for
/// varint/zigzag/fixed64, u32 for fixed32.
fn proto_scalar_raw(s: ScalarType, enc: ProtoEncoding) -> &'static str {
    match (enc, s.proto_size()) {
        (ProtoEncoding::Fixed, 4) => "nanobuf::proto::expect_i32(value)?",
        (ProtoEncoding::Fixed, _) => "nanobuf::proto::expect_i64(value)?",
        _ => "nanobuf::proto::expect_varint(value)?",
    }
}

fn proto_read_field(w: &mut CodeWriter, schema: &Schema, m: &Message, f: &Field) {
    let field = rust_ident(&f.name);
    let id = f.id;
    match f.ty {
        Type::Scalar(s) => {
            let raw = proto_scalar_raw(s, f.proto);
            let expr = proto_scalar_decode(s, f.proto, raw);
            if f.optional {
                w.line(format!("{id} => message.{field} = Some({expr}),"));
            } else {
                w.line(format!("{id} => message.{field} = {expr},"));
            }
        }
        Type::Enum(id_) => {
            let path = enum_path(schema, m, id_);
            let backing = rust_scalar(schema.enumeration(id_).backing);
            let expr = format!("{path}(nanobuf::proto::expect_varint(value)? as {backing})");
            if f.optional {
                w.line(format!("{id} => message.{field} = Some({expr}),"));
            } else {
                w.line(format!("{id} => message.{field} = {expr},"));
            }
        }
        Type::String => {
            let expr = "nanobuf::proto::expect_string(value)?";
            if f.optional {
                w.line(format!("{id} => message.{field} = Some({expr}),"));
            } else {
                w.line(format!("{id} => message.{field} = {expr},"));
            }
        }
        Type::Bytes => {
            let expr = "nanobuf::proto::expect_len(value)?.to_vec()";
            if f.optional {
                w.line(format!("{id} => message.{field} = Some({expr}),"));
            } else {
                w.line(format!("{id} => message.{field} = {expr},"));
            }
        }
        Type::Message(target) => {
            let path = message_path(schema, m, target);
            let decode = format!("{path}::decode_proto3(nanobuf::proto::expect_len(value)?)?");
            let wrap = if f.boxed {
                format!("Box::new({decode})")
            } else {
                decode
            };
            w.line(format!("{id} => message.{field} = Some({wrap}),"));
        }
        Type::List(elem) => match elem {
            ElemType::Scalar(s) => {
                let reader = match (f.proto, s.proto_size()) {
                    (ProtoEncoding::Fixed, 4) => "read_packed_fixed32",
                    (ProtoEncoding::Fixed, _) => "read_packed_fixed64",
                    _ => "read_packed_varints",
                };
                let expr = proto_scalar_decode(s, f.proto, "v");
                w.line(format!(
                    "{id} => nanobuf::proto::{reader}(value, |v| message.{field}.push({expr}))?,"
                ));
            }
            ElemType::Enum(target) => {
                let path = enum_path(schema, m, target);
                let backing = rust_scalar(schema.enumeration(target).backing);
                w.line(format!(
                    "{id} => nanobuf::proto::read_packed_varints(value, |v| message.{field}.push({path}(v as {backing})))?,"
                ));
            }
            ElemType::String => {
                w.line(format!(
                    "{id} => message.{field}.push(nanobuf::proto::expect_string(value)?),"
                ));
            }
            ElemType::Bytes => {
                w.line(format!(
                    "{id} => message.{field}.push(nanobuf::proto::expect_len(value)?.to_vec()),"
                ));
            }
            ElemType::Message(target) => {
                let path = message_path(schema, m, target);
                w.line(format!(
                    "{id} => message.{field}.push({path}::decode_proto3(nanobuf::proto::expect_len(value)?)?),"
                ));
            }
        },
    }
}

fn proto_write_field(w: &mut CodeWriter, f: &Field) {
    let field = rust_ident(&f.name);
    let id = f.id;
    let tag_writer = |s: ScalarType, enc: ProtoEncoding, value: &str| -> String {
        match (enc, s.proto_size()) {
            (ProtoEncoding::Fixed, 4) => format!(
                "nanobuf::proto::write_i32_field(out, {id}, {});",
                proto_scalar_encode(s, enc, value)
            ),
            (ProtoEncoding::Fixed, _) => format!(
                "nanobuf::proto::write_i64_field(out, {id}, {});",
                proto_scalar_encode(s, enc, value)
            ),
            _ => format!(
                "nanobuf::proto::write_varint_field(out, {id}, {});",
                proto_scalar_encode(s, enc, value)
            ),
        }
    };
    match f.ty {
        Type::Scalar(s) => {
            if f.optional {
                w.open(format!("if let Some(value) = self.{field} {{"));
                w.line(tag_writer(s, f.proto, "value"));
                w.close("}");
            } else {
                let condition = if s == ScalarType::Bool {
                    format!("if self.{field} {{")
                } else if s == ScalarType::F16 {
                    // Numeric comparison, so -0.0 is skipped like the
                    // other float widths.
                    format!("if self.{field}.to_f32() != 0.0 {{")
                } else if s.is_float() {
                    format!("if self.{field} != 0.0 {{")
                } else {
                    format!("if self.{field} != 0 {{")
                };
                w.open(condition);
                w.line(tag_writer(s, f.proto, &format!("self.{field}")));
                w.close("}");
            }
        }
        Type::Enum(_) => {
            if f.optional {
                w.open(format!("if let Some(value) = self.{field} {{"));
                w.line(format!(
                    "nanobuf::proto::write_varint_field(out, {id}, i64::from(value.0) as u64);"
                ));
                w.close("}");
            } else {
                w.open(format!("if self.{field}.0 != 0 {{"));
                w.line(format!(
                    "nanobuf::proto::write_varint_field(out, {id}, i64::from(self.{field}.0) as u64);"
                ));
                w.close("}");
            }
        }
        Type::String => {
            if f.optional {
                w.open(format!("if let Some(value) = &self.{field} {{"));
                w.line(format!(
                    "nanobuf::proto::write_len_field(out, {id}, value.as_bytes());"
                ));
                w.close("}");
            } else {
                w.open(format!("if !self.{field}.is_empty() {{"));
                w.line(format!(
                    "nanobuf::proto::write_len_field(out, {id}, self.{field}.as_bytes());"
                ));
                w.close("}");
            }
        }
        Type::Bytes => {
            if f.optional {
                w.open(format!("if let Some(value) = &self.{field} {{"));
                w.line(format!(
                    "nanobuf::proto::write_len_field(out, {id}, value);"
                ));
                w.close("}");
            } else {
                w.open(format!("if !self.{field}.is_empty() {{"));
                w.line(format!(
                    "nanobuf::proto::write_len_field(out, {id}, &self.{field});"
                ));
                w.close("}");
            }
        }
        Type::Message(_) => {
            w.open(format!("if let Some(value) = &self.{field} {{"));
            w.line(format!(
                "nanobuf::proto::write_len_field_with(out, {id}, |out| value.write_proto3(out));"
            ));
            w.close("}");
        }
        Type::List(elem) => {
            w.open(format!("if !self.{field}.is_empty() {{"));
            match elem {
                ElemType::Scalar(s) => {
                    let item = proto_scalar_encode(s, f.proto, "item");
                    let body = match f.proto {
                        ProtoEncoding::Fixed => {
                            format!("out.extend_from_slice(&({item}).to_le_bytes());")
                        }
                        _ => format!("nanobuf::proto::write_varint(out, {item});"),
                    };
                    w.open(format!(
                        "nanobuf::proto::write_len_field_with(out, {id}, |out| {{"
                    ));
                    w.open(format!("for &item in &self.{field} {{"));
                    w.line(body);
                    w.close("}");
                    w.close("});");
                }
                ElemType::Enum(_) => {
                    w.open(format!(
                        "nanobuf::proto::write_len_field_with(out, {id}, |out| {{"
                    ));
                    w.open(format!("for item in &self.{field} {{"));
                    w.line("nanobuf::proto::write_varint(out, i64::from(item.0) as u64);");
                    w.close("}");
                    w.close("});");
                }
                ElemType::String => {
                    w.open(format!("for item in &self.{field} {{"));
                    w.line(format!(
                        "nanobuf::proto::write_len_field(out, {id}, item.as_bytes());"
                    ));
                    w.close("}");
                }
                ElemType::Bytes => {
                    w.open(format!("for item in &self.{field} {{"));
                    w.line(format!("nanobuf::proto::write_len_field(out, {id}, item);"));
                    w.close("}");
                }
                ElemType::Message(_) => {
                    w.open(format!("for item in &self.{field} {{"));
                    w.line(format!(
                        "nanobuf::proto::write_len_field_with(out, {id}, |out| item.write_proto3(out));"
                    ));
                    w.close("}");
                }
            }
            w.close("}");
        }
    }
}
