//! C# code generator. See `rust.rs` for the reference backend.
//!
//! Emits one file containing a namespace per package. Every message gets an
//! owned class (`Packet`), a zero-copy ref struct view (`PacketView`), and
//! proto3 migration codecs. All wire offsets come from the schema IR.
//! Message-typed view accessors use the `TryGet` pattern because ref structs
//! cannot be wrapped in `Nullable<T>`.

use nanobuf_schema::{
    DataSlot, ElemType, Enum, EnumId, Field, Message, MessageId, ProtoEncoding, ScalarType, Schema,
    Type,
};

use crate::names::{camel, csharp_ident, pascal};
use crate::writer::CodeWriter;

/// View members that field accessors must not shadow.
const RESERVED_VIEW_MEMBERS: &[&str] = &["Parse", "Data", "ToOwned", "FromView"];

pub fn generate(schema: &Schema) -> String {
    let mut w = CodeWriter::new("    ");
    w.line("// @generated by nanoc. DO NOT EDIT.");
    w.line("// Wire layout is fixed by the schema; see docs/wire-format.md.");
    w.line("#nullable enable");
    w.blank();
    w.line("using System;");
    w.line("using System.Collections.Generic;");
    w.line("using System.Text;");
    for package in schema.packages() {
        w.blank();
        w.open(format!("namespace {} {{", namespace(package)));
        let mut first = true;
        for e in schema.enums.iter().filter(|e| e.package == package) {
            if !first {
                w.blank();
            }
            first = false;
            enum_def(&mut w, e);
        }
        for m in &schema.messages {
            if m.package != package {
                continue;
            }
            if !first {
                w.blank();
            }
            first = false;
            message_def(&mut w, schema, m);
        }
        w.close("}");
    }
    w.finish()
}

/// `demo.telemetry` -> `Demo.Telemetry`.
fn namespace(package: &str) -> String {
    package.split('.').map(pascal).collect::<Vec<_>>().join(".")
}

fn cs_scalar(s: ScalarType) -> &'static str {
    match s {
        ScalarType::Bool => "bool",
        ScalarType::U8 => "byte",
        ScalarType::U16 => "ushort",
        ScalarType::U32 => "uint",
        ScalarType::U64 => "ulong",
        ScalarType::I8 => "sbyte",
        ScalarType::I16 => "short",
        ScalarType::I32 => "int",
        ScalarType::I64 => "long",
        ScalarType::F32 => "float",
        ScalarType::F64 => "double",
    }
}

/// Path to a message or enum type from inside `current`'s namespace.
fn type_path(current: &Message, package: &str, name: &str) -> String {
    let name = pascal(name);
    if package == current.package {
        name
    } else {
        format!("global::{}.{name}", namespace(package))
    }
}

fn message_path(schema: &Schema, current: &Message, id: MessageId) -> String {
    let target = schema.message(id);
    type_path(current, &target.package, &target.name)
}

fn enum_path(schema: &Schema, current: &Message, id: EnumId) -> String {
    let target = schema.enumeration(id);
    type_path(current, &target.package, &target.name)
}

fn enum_def(w: &mut CodeWriter, e: &Enum) {
    let name = pascal(&e.name);
    let backing = cs_scalar(e.backing);
    w.doc(&e.docs, "///");
    w.line("/// Open enum: values outside the schema are preserved.");
    w.open(format!(
        "public readonly struct {name} : IEquatable<{name}> {{"
    ));
    w.line(format!("public readonly {backing} Value;"));
    w.blank();
    w.open(format!("public {name}({backing} value) {{"));
    w.line("Value = value;");
    w.close("}");
    w.blank();
    for v in &e.variants {
        w.doc(&v.docs, "///");
        w.line(format!(
            "public static readonly {name} {} = new({});",
            pascal(&v.name),
            v.value
        ));
    }
    w.blank();
    w.line("/// Schema name of the value, if it has one.");
    w.open("public string? Name() => Value switch {");
    for v in &e.variants {
        w.line(format!("{} => \"{}\",", v.value, v.name));
    }
    w.line("_ => null,");
    w.close("};");
    w.blank();
    w.line(format!(
        "public bool Equals({name} other) => Value == other.Value;"
    ));
    w.blank();
    w.line(format!(
        "public override bool Equals(object? obj) => obj is {name} other && Equals(other);"
    ));
    w.blank();
    w.line("public override int GetHashCode() => Value.GetHashCode();");
    w.blank();
    w.line(format!(
        "public static bool operator ==({name} left, {name} right) => left.Equals(right);"
    ));
    w.blank();
    w.line(format!(
        "public static bool operator !=({name} left, {name} right) => !left.Equals(right);"
    ));
    w.blank();
    w.line("public override string ToString() => Name() ?? Value.ToString();");
    w.close("}");
}

/// Owned property type plus its initializer.
fn owned_type(schema: &Schema, m: &Message, f: &Field) -> (String, &'static str) {
    match f.ty {
        Type::Scalar(s) => {
            let base = cs_scalar(s);
            if f.optional {
                (format!("{base}?"), "")
            } else {
                (base.to_string(), "")
            }
        }
        Type::Enum(id) => {
            let base = enum_path(schema, m, id);
            if f.optional {
                (format!("{base}?"), "")
            } else {
                (base, "")
            }
        }
        Type::String => {
            if f.optional {
                ("string?".to_string(), "")
            } else {
                ("string".to_string(), " = \"\";")
            }
        }
        Type::Bytes => {
            if f.optional {
                ("byte[]?".to_string(), "")
            } else {
                ("byte[]".to_string(), " = Array.Empty<byte>();")
            }
        }
        // Classes are references, so recursion needs no boxing in C#.
        Type::Message(id) => (format!("{}?", message_path(schema, m, id)), ""),
        Type::List(elem) => {
            let elem = match elem {
                ElemType::Scalar(s) => cs_scalar(s).to_string(),
                ElemType::Enum(id) => enum_path(schema, m, id),
                ElemType::String => "string".to_string(),
                ElemType::Bytes => "byte[]".to_string(),
                ElemType::Message(id) => message_path(schema, m, id),
            };
            (format!("List<{elem}>"), " = new();")
        }
    }
}

/// Local variable name for a field value bound by a pattern match.
fn local_name(f: &Field) -> String {
    format!("{}Value", camel(&f.name))
}

/// View accessor name for a field, avoiding builtins.
fn accessor_name(f: &Field) -> String {
    let name = csharp_ident(&f.name);
    if RESERVED_VIEW_MEMBERS.contains(&name.as_str()) {
        format!("Get{name}")
    } else {
        name
    }
}

fn message_def(w: &mut CodeWriter, schema: &Schema, m: &Message) {
    let name = pascal(&m.name);
    let view_name = format!("{name}View");

    // Owned class.
    w.doc(&m.docs, "///");
    w.open(format!(
        "public sealed class {name} : IEquatable<{name}?> {{"
    ));
    for f in &m.fields {
        w.doc(&f.docs, "///");
        let (ty, init) = owned_type(schema, m, f);
        w.line(format!(
            "public {ty} {} {{ get; set; }}{init}",
            csharp_ident(&f.name)
        ));
    }
    w.blank();
    w.open("public byte[] Encode() {");
    w.line("var writer = new global::Nanobuf.Writer();");
    w.line("WriteTo(writer);");
    w.line("return writer.ToArray();");
    w.close("}");
    w.blank();
    w.line(format!(
        "public static {name} Decode(ReadOnlySpan<byte> data) => {view_name}.Parse(data).ToOwned();"
    ));
    w.blank();
    w.open("internal void WriteTo(global::Nanobuf.Writer w) {");
    w.line(format!("w.Begin({});", m.fixed_len));
    for f in &m.fields {
        write_field(w, f);
    }
    w.close("}");
    proto_codecs(w, schema, m, &name);
    equality(w, m, &name);
    w.close("}");
    w.blank();

    // Zero-copy view.
    w.line(format!("/// Zero-copy reader for <see cref=\"{name}\"/>."));
    w.open(format!("public readonly ref struct {view_name} {{"));
    w.line("private readonly ReadOnlySpan<byte> _data;");
    w.line("private readonly int _fixedLen;");
    w.blank();
    w.open(format!(
        "private {view_name}(ReadOnlySpan<byte> data, int fixedLen) {{"
    ));
    w.line("_data = data;");
    w.line("_fixedLen = fixedLen;");
    w.close("}");
    w.blank();
    w.line(format!(
        "public static {view_name} Parse(ReadOnlySpan<byte> data) => new(data, global::Nanobuf.Wire.ParseHeader(data));"
    ));
    w.blank();
    w.line("/// Raw message bytes, for forwarding without re-encoding.");
    w.line("public ReadOnlySpan<byte> Data => _data;");
    for f in &m.fields {
        w.blank();
        view_accessor(w, schema, m, f);
    }
    w.blank();
    to_owned(w, m, &name);
    w.close("}");
}

/// Emits the `WriteTo` statements for one field.
fn write_field(w: &mut CodeWriter, f: &Field) {
    let prop = csharp_ident(&f.name);
    let local = local_name(f);
    match (f.layout.data, f.ty) {
        (DataSlot::Bit(bit), _) => {
            if let Some(p) = f.layout.presence {
                w.open(format!("if ({prop} is {{ }} {local}) {{"));
                w.line(format!("w.PutBit({}, {}, true);", p.byte, p.bit));
                w.line(format!("w.PutBit({}, {}, {local});", bit.byte, bit.bit));
                w.close("}");
            } else {
                w.line(format!("w.PutBit({}, {}, {prop});", bit.byte, bit.bit));
            }
        }
        (DataSlot::Bytes { offset, .. }, _) => {
            if let Some(p) = f.layout.presence {
                w.open(format!("if ({prop} is {{ }} {local}) {{"));
                w.line(format!("w.PutBit({}, {}, true);", p.byte, p.bit));
                w.line(format!("w.PutScalar({offset}, {local});"));
                w.close("}");
            } else {
                w.line(format!("w.PutScalar({offset}, {prop});"));
            }
        }
        (DataSlot::Offset { offset }, Type::String) => {
            if f.optional {
                w.open(format!("if ({prop} is {{ }} {local}) {{"));
                w.line(format!("w.PutString({offset}, {local}, true);"));
                w.close("}");
            } else {
                w.line(format!("w.PutString({offset}, {prop}, false);"));
            }
        }
        (DataSlot::Offset { offset }, Type::Bytes) => {
            if f.optional {
                w.open(format!("if ({prop} is {{ }} {local}) {{"));
                w.line(format!("w.PutBytes({offset}, {local}, true);"));
                w.close("}");
            } else {
                w.line(format!("w.PutBytes({offset}, {prop}, false);"));
            }
        }
        (DataSlot::Offset { offset }, Type::Message(_)) => {
            w.open(format!("if ({prop} is {{ }} {local}) {{"));
            w.line(format!("w.PutMessage({offset}, {local}.WriteTo);"));
            w.close("}");
        }
        (DataSlot::Offset { offset }, Type::List(elem)) => match elem {
            ElemType::Scalar(_) | ElemType::Enum(_) => {
                w.line(format!("w.PutScalarList({offset}, {prop});"));
            }
            ElemType::String => {
                w.line(format!(
                    "w.PutOffsetList({offset}, {prop}, static (writer, item) => writer.HeapString(item));"
                ));
            }
            ElemType::Bytes => {
                w.line(format!(
                    "w.PutOffsetList({offset}, {prop}, static (writer, item) => writer.HeapBytes(item));"
                ));
            }
            ElemType::Message(_) => {
                w.line(format!(
                    "w.PutOffsetList({offset}, {prop}, static (writer, item) => writer.HeapMessage(item.WriteTo));"
                ));
            }
        },
        (slot, ty) => unreachable!("invalid slot {slot:?} for type {ty:?}"),
    }
}

fn view_accessor(w: &mut CodeWriter, schema: &Schema, m: &Message, f: &Field) {
    let method = accessor_name(f);
    w.doc(&f.docs, "///");
    match (f.layout.data, f.ty) {
        (DataSlot::Bit(bit), _) => {
            let read = format!(
                "global::Nanobuf.Wire.BitAt(_data, _fixedLen, {}, {})",
                bit.byte, bit.bit
            );
            if let Some(p) = f.layout.presence {
                w.line(format!(
                    "public bool? {method} => global::Nanobuf.Wire.BitAt(_data, _fixedLen, {}, {}) ? {read} : (bool?)null;",
                    p.byte, p.bit
                ));
            } else {
                w.line(format!("public bool {method} => {read};"));
            }
        }
        (DataSlot::Bytes { offset, .. }, ty) => {
            let value_type = match ty {
                Type::Scalar(s) => cs_scalar(s).to_string(),
                Type::Enum(id) => enum_path(schema, m, id),
                _ => unreachable!("byte slots hold scalars and enums"),
            };
            let read =
                format!("global::Nanobuf.Wire.ScalarAt<{value_type}>(_data, _fixedLen, {offset})");
            if let Some(p) = f.layout.presence {
                w.line(format!(
                    "public {value_type}? {method} => global::Nanobuf.Wire.BitAt(_data, _fixedLen, {}, {}) ? {read} : ({value_type}?)null;",
                    p.byte, p.bit
                ));
            } else {
                w.line(format!("public {value_type} {method} => {read};"));
            }
        }
        (DataSlot::Offset { offset }, Type::String) => {
            if f.optional {
                w.line(format!(
                    "public string? {method} => global::Nanobuf.Wire.StrAt(_data, _fixedLen, {offset});"
                ));
            } else {
                w.line(format!(
                    "public string {method} => global::Nanobuf.Wire.StrAt(_data, _fixedLen, {offset}) ?? \"\";"
                ));
            }
        }
        (DataSlot::Offset { offset }, Type::Bytes) => {
            if f.optional {
                w.line(format!(
                    "public bool TryGet{}(out ReadOnlySpan<byte> value) => global::Nanobuf.Wire.TryHeapAt(_data, _fixedLen, {offset}, out value);",
                    csharp_ident(&f.name)
                ));
            } else {
                w.line(format!(
                    "public ReadOnlySpan<byte> {method} => global::Nanobuf.Wire.TryHeapAt(_data, _fixedLen, {offset}, out var value) ? value : default;"
                ));
            }
        }
        (DataSlot::Offset { offset }, Type::Message(id)) => {
            let view = format!("{}View", message_path(schema, m, id));
            w.open(format!(
                "public bool TryGet{}(out {view} value) {{",
                csharp_ident(&f.name)
            ));
            w.open(format!(
                "if (!global::Nanobuf.Wire.TryHeapAt(_data, _fixedLen, {offset}, out var bytes)) {{"
            ));
            w.line("value = default;");
            w.line("return false;");
            w.close("}");
            w.line(format!("value = {view}.Parse(bytes);"));
            w.line("return true;");
            w.close("}");
        }
        (DataSlot::Offset { offset }, Type::List(elem)) => match elem {
            ElemType::Scalar(_) | ElemType::Enum(_) => {
                let elem_ty = match elem {
                    ElemType::Scalar(s) => cs_scalar(s).to_string(),
                    ElemType::Enum(id) => enum_path(schema, m, id),
                    _ => unreachable!(),
                };
                w.line(format!(
                    "public global::Nanobuf.ScalarList<{elem_ty}> {method} => global::Nanobuf.Wire.ScalarListAt<{elem_ty}>(_data, _fixedLen, {offset});"
                ));
            }
            ElemType::String => {
                w.line(format!(
                    "public global::Nanobuf.StrList {method} => new(global::Nanobuf.Wire.OffsetListAt(_data, _fixedLen, {offset}));"
                ));
            }
            ElemType::Bytes => {
                w.line(format!(
                    "public global::Nanobuf.BytesList {method} => new(global::Nanobuf.Wire.OffsetListAt(_data, _fixedLen, {offset}));"
                ));
            }
            ElemType::Message(id) => {
                let view = format!("{}View", message_path(schema, m, id));
                w.line(format!(
                    "public global::Nanobuf.OffsetList {method} => global::Nanobuf.Wire.OffsetListAt(_data, _fixedLen, {offset});"
                ));
                w.blank();
                w.line(format!(
                    "public {view} {method}At(int index) => {view}.Parse({method}.BytesAt(index));"
                ));
            }
        },
        (slot, ty) => unreachable!("invalid slot {slot:?} for type {ty:?}"),
    }
}

fn to_owned(w: &mut CodeWriter, m: &Message, name: &str) {
    w.line(format!(
        "/// Copies every field into an owned <see cref=\"{name}\"/>."
    ));
    w.open(format!("public {name} ToOwned() {{"));
    w.line(format!("var message = new {name}();"));
    for f in &m.fields {
        let prop = csharp_ident(&f.name);
        let method = accessor_name(f);
        let local = local_name(f);
        match f.ty {
            Type::Scalar(_) | Type::Enum(_) | Type::String => {
                w.line(format!("message.{prop} = {method};"));
            }
            Type::Bytes => {
                if f.optional {
                    w.open(format!("if (TryGet{prop}(out var {local})) {{"));
                    w.line(format!("message.{prop} = {local}.ToArray();"));
                    w.close("}");
                } else {
                    w.line(format!("message.{prop} = {method}.ToArray();"));
                }
            }
            Type::Message(_) => {
                w.open(format!("if (TryGet{prop}(out var {local})) {{"));
                w.line(format!("message.{prop} = {local}.ToOwned();"));
                w.close("}");
            }
            Type::List(elem) => match elem {
                ElemType::Scalar(_) | ElemType::Enum(_) | ElemType::String | ElemType::Bytes => {
                    w.line(format!("message.{prop} = {method}.ToList();"));
                }
                ElemType::Message(_) => {
                    w.line(format!("var {local} = {method};"));
                    w.open(format!("for (int i = 0; i < {local}.Count; i++) {{"));
                    w.line(format!("message.{prop}.Add({method}At(i).ToOwned());"));
                    w.close("}");
                }
            },
        }
    }
    w.line("return message;");
    w.close("}");
}

/// Value-style equality on the owned class, deep enough for tests.
fn equality(w: &mut CodeWriter, m: &Message, name: &str) {
    w.blank();
    if m.fields.is_empty() {
        w.line(format!(
            "public bool Equals({name}? other) => other is not null;"
        ));
    } else {
        w.open(format!("public bool Equals({name}? other) {{"));
        w.line("return other is not null");
        for (i, f) in m.fields.iter().enumerate() {
            let prop = csharp_ident(&f.name);
            let expr = match f.ty {
                Type::Scalar(_) | Type::Enum(_) | Type::String => {
                    format!("{prop} == other.{prop}")
                }
                Type::Bytes => format!("global::Nanobuf.Eq.Bytes({prop}, other.{prop})"),
                Type::Message(_) => format!("Equals({prop}, other.{prop})"),
                Type::List(ElemType::Bytes) => {
                    format!("global::Nanobuf.Eq.ByteLists({prop}, other.{prop})")
                }
                Type::List(_) => format!("global::Nanobuf.Eq.Lists({prop}, other.{prop})"),
            };
            let tail = if i + 1 == m.fields.len() { ";" } else { "" };
            // Continuation lines carry one extra manual indent.
            w.line(format!("    && {expr}{tail}"));
        }
        w.close("}");
    }
    w.blank();
    w.line(format!(
        "public override bool Equals(object? obj) => Equals(obj as {name});"
    ));
    w.blank();
    let hashed: Vec<String> = m
        .fields
        .iter()
        .filter(|f| matches!(f.ty, Type::Scalar(_) | Type::Enum(_) | Type::String))
        .take(8)
        .map(|f| csharp_ident(&f.name))
        .collect();
    if hashed.is_empty() {
        w.line("public override int GetHashCode() => 0;");
    } else {
        w.line(format!(
            "public override int GetHashCode() => HashCode.Combine({});",
            hashed.join(", ")
        ));
    }
}

/// Proto3 migration codecs on the owned class.
fn proto_codecs(w: &mut CodeWriter, schema: &Schema, m: &Message, name: &str) {
    w.blank();
    w.line("/// Encodes to the proto3 wire format (migration mode only).");
    w.open("public byte[] EncodeProto3() {");
    w.line("var output = new global::Nanobuf.ByteWriter();");
    w.line("WriteProto3(output);");
    w.line("return output.ToArray();");
    w.close("}");
    w.blank();
    w.open("internal void WriteProto3(global::Nanobuf.ByteWriter output) {");
    if m.fields.is_empty() {
        w.line("_ = output;");
    }
    for f in &m.fields {
        proto_write_field(w, f);
    }
    w.close("}");
    w.blank();
    w.line("/// Decodes the proto3 wire format (migration mode only).");
    w.open(format!(
        "public static {name} DecodeProto3(ReadOnlySpan<byte> data) {{"
    ));
    if m.fields.is_empty() {
        w.line("var reader = new global::Nanobuf.ProtoReader(data);");
        w.line("while (reader.Next(out _, out _)) { }");
        w.line(format!("return new {name}();"));
        w.close("}");
        return;
    }
    w.line(format!("var message = new {name}();"));
    w.line("var reader = new global::Nanobuf.ProtoReader(data);");
    w.open("while (reader.Next(out uint field, out var value)) {");
    w.open("switch (field) {");
    for f in &m.fields {
        proto_read_field(w, schema, m, f);
    }
    w.line("default: // unknown field, skipped");
    w.line("    break;");
    w.close("}");
    w.close("}");
    w.line("return message;");
    w.close("}");
}

/// Expression converting a raw wire scalar (`ulong`, or `uint` for fixed32)
/// into the field's C# type, given the proto encoding.
fn proto_scalar_decode(s: ScalarType, enc: ProtoEncoding, v: &str) -> String {
    let ty = cs_scalar(s);
    match (enc, s) {
        (_, ScalarType::Bool) => format!("{v} != 0"),
        (ProtoEncoding::Fixed, ScalarType::F32) => format!("BitConverter.UInt32BitsToSingle({v})"),
        (ProtoEncoding::Fixed, ScalarType::F64) => format!("BitConverter.UInt64BitsToDouble({v})"),
        (ProtoEncoding::ZigZag, _) => format!("({ty})global::Nanobuf.Proto.ZigzagDecode({v})"),
        _ => format!("({ty}){v}"),
    }
}

/// Expression converting `value` of the field's C# type to the `ulong` (or
/// `uint` for fixed32) the wire writer takes.
fn proto_scalar_encode(s: ScalarType, enc: ProtoEncoding, value: &str) -> String {
    match (enc, s) {
        (_, ScalarType::Bool) => format!("{value} ? 1UL : 0UL"),
        (ProtoEncoding::Fixed, ScalarType::F32) => {
            format!("BitConverter.SingleToUInt32Bits({value})")
        }
        (ProtoEncoding::Fixed, ScalarType::F64) => {
            format!("BitConverter.DoubleToUInt64Bits({value})")
        }
        (ProtoEncoding::Fixed, s) if s.size() == 4 => format!("(uint){value}"),
        (ProtoEncoding::Fixed, _) => format!("(ulong){value}"),
        (ProtoEncoding::ZigZag, _) => format!("global::Nanobuf.Proto.ZigzagEncode({value})"),
        // Signed varints sign-extend through long to ulong.
        (ProtoEncoding::Varint, ScalarType::I64) => format!("(ulong){value}"),
        (ProtoEncoding::Varint, s) if s.is_signed() => format!("(ulong)(long){value}"),
        (ProtoEncoding::Varint, _) => value.to_string(),
        (ProtoEncoding::LengthDelimited, _) => unreachable!("scalars are never length-delimited"),
    }
}

/// Wire reader call yielding the raw scalar for the encoding.
fn proto_scalar_raw(s: ScalarType, enc: ProtoEncoding) -> &'static str {
    match (enc, s.size()) {
        (ProtoEncoding::Fixed, 4) => "global::Nanobuf.Proto.ExpectI32(value)",
        (ProtoEncoding::Fixed, _) => "global::Nanobuf.Proto.ExpectI64(value)",
        _ => "global::Nanobuf.Proto.ExpectVarint(value)",
    }
}

fn proto_read_field(w: &mut CodeWriter, schema: &Schema, m: &Message, f: &Field) {
    let prop = csharp_ident(&f.name);
    let stmt = match f.ty {
        Type::Scalar(s) => {
            let raw = proto_scalar_raw(s, f.proto);
            format!("message.{prop} = {};", proto_scalar_decode(s, f.proto, raw))
        }
        Type::Enum(target) => {
            let path = enum_path(schema, m, target);
            let backing = cs_scalar(schema.enumeration(target).backing);
            format!(
                "message.{prop} = new {path}(({backing})global::Nanobuf.Proto.ExpectVarint(value));"
            )
        }
        Type::String => format!("message.{prop} = global::Nanobuf.Proto.ExpectString(value);"),
        Type::Bytes => {
            format!("message.{prop} = global::Nanobuf.Proto.ExpectLen(value).ToArray();")
        }
        Type::Message(target) => {
            let path = message_path(schema, m, target);
            format!("message.{prop} = {path}.DecodeProto3(global::Nanobuf.Proto.ExpectLen(value));")
        }
        Type::List(elem) => match elem {
            ElemType::Scalar(s) => {
                let reader = match (f.proto, s.size()) {
                    (ProtoEncoding::Fixed, 4) => "ReadPackedFixed32",
                    (ProtoEncoding::Fixed, _) => "ReadPackedFixed64",
                    _ => "ReadPackedVarints",
                };
                let expr = proto_scalar_decode(s, f.proto, "item");
                format!(
                    "global::Nanobuf.Proto.{reader}(value, item => message.{prop}.Add({expr}));"
                )
            }
            ElemType::Enum(target) => {
                let path = enum_path(schema, m, target);
                let backing = cs_scalar(schema.enumeration(target).backing);
                format!(
                    "global::Nanobuf.Proto.ReadPackedVarints(value, item => message.{prop}.Add(new {path}(({backing})item)));"
                )
            }
            ElemType::String => {
                format!("message.{prop}.Add(global::Nanobuf.Proto.ExpectString(value));")
            }
            ElemType::Bytes => {
                format!("message.{prop}.Add(global::Nanobuf.Proto.ExpectLen(value).ToArray());")
            }
            ElemType::Message(target) => {
                let path = message_path(schema, m, target);
                format!(
                    "message.{prop}.Add({path}.DecodeProto3(global::Nanobuf.Proto.ExpectLen(value)));"
                )
            }
        },
    };
    // Case bodies carry one extra manual indent.
    w.line(format!("case {}:", f.id));
    w.line(format!("    {stmt}"));
    w.line("    break;");
}

fn proto_write_field(w: &mut CodeWriter, f: &Field) {
    let prop = csharp_ident(&f.name);
    let local = local_name(f);
    let id = f.id;
    let tag_writer = |s: ScalarType, enc: ProtoEncoding, value: &str| -> String {
        let encoded = proto_scalar_encode(s, enc, value);
        match (enc, s.size()) {
            (ProtoEncoding::Fixed, 4) => {
                format!("global::Nanobuf.Proto.WriteI32Field(output, {id}, {encoded});")
            }
            (ProtoEncoding::Fixed, _) => {
                format!("global::Nanobuf.Proto.WriteI64Field(output, {id}, {encoded});")
            }
            _ => format!("global::Nanobuf.Proto.WriteVarintField(output, {id}, {encoded});"),
        }
    };
    match f.ty {
        Type::Scalar(s) => {
            if f.optional {
                w.open(format!("if ({prop} is {{ }} {local}) {{"));
                w.line(tag_writer(s, f.proto, &local));
                w.close("}");
            } else {
                let condition = if s == ScalarType::Bool {
                    format!("if ({prop}) {{")
                } else {
                    format!("if ({prop} != 0) {{")
                };
                w.open(condition);
                w.line(tag_writer(s, f.proto, &prop));
                w.close("}");
            }
        }
        Type::Enum(_) => {
            if f.optional {
                w.open(format!("if ({prop} is {{ }} {local}) {{"));
                w.line(format!(
                    "global::Nanobuf.Proto.WriteVarintField(output, {id}, (ulong)(long){local}.Value);"
                ));
                w.close("}");
            } else {
                w.open(format!("if ({prop}.Value != 0) {{"));
                w.line(format!(
                    "global::Nanobuf.Proto.WriteVarintField(output, {id}, (ulong)(long){prop}.Value);"
                ));
                w.close("}");
            }
        }
        Type::String => {
            if f.optional {
                w.open(format!("if ({prop} is {{ }} {local}) {{"));
                w.line(format!(
                    "global::Nanobuf.Proto.WriteLenField(output, {id}, Encoding.UTF8.GetBytes({local}));"
                ));
                w.close("}");
            } else {
                w.open(format!("if ({prop}.Length != 0) {{"));
                w.line(format!(
                    "global::Nanobuf.Proto.WriteLenField(output, {id}, Encoding.UTF8.GetBytes({prop}));"
                ));
                w.close("}");
            }
        }
        Type::Bytes => {
            if f.optional {
                w.open(format!("if ({prop} is {{ }} {local}) {{"));
                w.line(format!(
                    "global::Nanobuf.Proto.WriteLenField(output, {id}, {local});"
                ));
                w.close("}");
            } else {
                w.open(format!("if ({prop}.Length != 0) {{"));
                w.line(format!(
                    "global::Nanobuf.Proto.WriteLenField(output, {id}, {prop});"
                ));
                w.close("}");
            }
        }
        Type::Message(_) => {
            w.open(format!("if ({prop} is {{ }} {local}) {{"));
            w.line(format!(
                "global::Nanobuf.Proto.WriteLenFieldWith(output, {id}, {local}.WriteProto3);"
            ));
            w.close("}");
        }
        Type::List(elem) => {
            w.open(format!("if ({prop}.Count != 0) {{"));
            match elem {
                ElemType::Scalar(s) => {
                    let item = proto_scalar_encode(s, f.proto, "item");
                    let body = match (f.proto, s.size()) {
                        (ProtoEncoding::Fixed, 4) => {
                            format!("global::Nanobuf.Proto.WriteFixed32(payload, {item});")
                        }
                        (ProtoEncoding::Fixed, _) => {
                            format!("global::Nanobuf.Proto.WriteFixed64(payload, {item});")
                        }
                        _ => format!("global::Nanobuf.Proto.WriteVarint(payload, {item});"),
                    };
                    w.open(format!(
                        "global::Nanobuf.Proto.WriteLenFieldWith(output, {id}, payload => {{"
                    ));
                    w.open(format!("foreach (var item in {prop}) {{"));
                    w.line(body);
                    w.close("}");
                    w.close("});");
                }
                ElemType::Enum(_) => {
                    w.open(format!(
                        "global::Nanobuf.Proto.WriteLenFieldWith(output, {id}, payload => {{"
                    ));
                    w.open(format!("foreach (var item in {prop}) {{"));
                    w.line("global::Nanobuf.Proto.WriteVarint(payload, (ulong)(long)item.Value);");
                    w.close("}");
                    w.close("});");
                }
                ElemType::String => {
                    w.open(format!("foreach (var item in {prop}) {{"));
                    w.line(format!(
                        "global::Nanobuf.Proto.WriteLenField(output, {id}, Encoding.UTF8.GetBytes(item));"
                    ));
                    w.close("}");
                }
                ElemType::Bytes => {
                    w.open(format!("foreach (var item in {prop}) {{"));
                    w.line(format!(
                        "global::Nanobuf.Proto.WriteLenField(output, {id}, item);"
                    ));
                    w.close("}");
                }
                ElemType::Message(_) => {
                    w.open(format!("foreach (var item in {prop}) {{"));
                    w.line(format!(
                        "global::Nanobuf.Proto.WriteLenFieldWith(output, {id}, item.WriteProto3);"
                    ));
                    w.close("}");
                }
            }
            w.close("}");
        }
    }
}
