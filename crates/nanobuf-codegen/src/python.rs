//! Python code generator. See `rust.rs` for the reference backend.
//!
//! Emits one flat module: Python has no per-package namespacing inside a
//! single file, so messages and enums from every package become top-level
//! classes. When two packages define the same type name, each colliding
//! class is prefixed with its pascal-cased package name (`demo.telemetry`
//! plus `Header` becomes `DemoTelemetryHeader`); unique names stay bare.
//! Each message gets an owned class (`Packet`), a zero-copy view
//! (`PacketView`), and proto3 migration codecs. All wire offsets come from
//! the schema IR; the generated module depends only on the `nanobuf`
//! runtime.

use nanobuf_schema::{
    DataSlot, ElemType, Enum, EnumId, Field, Message, MessageId, ProtoEncoding, ScalarType, Schema,
    Type,
};

use crate::names::{pascal, python_ident, shout};
use crate::writer::CodeWriter;

/// View attributes that field properties must not shadow.
const RESERVED_VIEW_ATTRS: &[&str] = &["data", "to_owned"];

/// Python blocks close by dedenting, so this tracks indentation explicitly
/// and prefixes it onto every line handed to the [`CodeWriter`].
struct Py {
    out: CodeWriter,
    depth: usize,
}

impl Py {
    fn new() -> Py {
        Py {
            out: CodeWriter::new("    "),
            depth: 0,
        }
    }

    fn line(&mut self, text: impl AsRef<str>) {
        self.out
            .line(format!("{}{}", "    ".repeat(self.depth), text.as_ref()));
    }

    fn blank(&mut self) {
        self.out.blank();
    }

    /// Writes a `...:` line and indents the following ones.
    fn open(&mut self, text: impl AsRef<str>) {
        self.line(text);
        self.depth += 1;
    }

    /// Ends a block: dedents without emitting text.
    fn end(&mut self) {
        self.depth -= 1;
    }

    fn finish(self) -> String {
        debug_assert_eq!(self.depth, 0, "unbalanced open/end");
        self.out.finish()
    }
}

pub fn generate(schema: &Schema) -> String {
    let mut w = Py::new();
    w.line("# @generated by nanoc. DO NOT EDIT.");
    w.line("# Wire layout is fixed by the schema; see docs/wire-format.md.");
    w.blank();
    w.line("import nanobuf");
    for e in &schema.enums {
        w.blank();
        w.blank();
        enum_def(&mut w, schema, e);
    }
    for m in &schema.messages {
        w.blank();
        w.blank();
        message_def(&mut w, schema, m);
    }
    w.finish()
}

/// Class name for a type, package-prefixed only on cross-package collision.
fn class_name(schema: &Schema, package: &str, name: &str) -> String {
    let class = pascal(name);
    let types = schema
        .messages
        .iter()
        .map(|m| (m.package.as_str(), m.name.as_str()))
        .chain(
            schema
                .enums
                .iter()
                .map(|e| (e.package.as_str(), e.name.as_str())),
        );
    let collides = types
        .into_iter()
        .any(|(p, n)| p != package && pascal(n) == class);
    if collides {
        format!("{}{class}", pascal(&package.replace('.', "_")))
    } else {
        class
    }
}

fn message_class(schema: &Schema, id: MessageId) -> String {
    let m = schema.message(id);
    class_name(schema, &m.package, &m.name)
}

fn enum_class(schema: &Schema, id: EnumId) -> String {
    let e = schema.enumeration(id);
    class_name(schema, &e.package, &e.name)
}

/// `struct` format character for a wire scalar.
fn fmt_char(s: ScalarType) -> &'static str {
    match s {
        ScalarType::Bool => "?",
        ScalarType::U8 => "B",
        ScalarType::U16 => "H",
        ScalarType::U32 => "I",
        ScalarType::U64 => "Q",
        ScalarType::I8 => "b",
        ScalarType::I16 => "h",
        ScalarType::I32 => "i",
        ScalarType::I64 => "q",
        ScalarType::F16 => "e",
        ScalarType::F32 => "f",
        ScalarType::F64 => "d",
    }
}

/// `struct` format character on the proto3 wire, where `f16` travels
/// widened to `float`.
fn proto_fmt_char(s: ScalarType) -> &'static str {
    match s {
        ScalarType::F16 => "f",
        _ => fmt_char(s),
    }
}

/// Expression for `value` as it goes onto the proto3 wire. Typed runtimes
/// hold `f16` fields already rounded; Python holds a full float, so it
/// rounds here to keep the encodings byte-identical.
fn proto_value_expr(s: ScalarType, value: &str) -> String {
    match s {
        ScalarType::F16 => format!("nanobuf.half_round({value})"),
        _ => value.to_string(),
    }
}

fn elem_fmt(schema: &Schema, elem: ElemType) -> &'static str {
    match elem {
        ElemType::Scalar(s) => fmt_char(s),
        ElemType::Enum(id) => fmt_char(schema.enumeration(id).backing),
        _ => unreachable!("only scalars and enums have a fixed element format"),
    }
}

fn default_expr(schema: &Schema, f: &Field) -> String {
    if f.optional {
        return "None".to_string();
    }
    match f.ty {
        Type::Scalar(ScalarType::Bool) => "False".to_string(),
        Type::Scalar(s) if s.is_float() => "0.0".to_string(),
        Type::Scalar(_) => "0".to_string(),
        Type::Enum(id) => format!("{}(0)", enum_class(schema, id)),
        Type::String => "\"\"".to_string(),
        Type::Bytes => "b\"\"".to_string(),
        // Lists default to a fresh [] in the body; None is the sentinel.
        Type::List(_) | Type::Message(_) => "None".to_string(),
    }
}

/// Emits a PEP 257 docstring; multi-line docs get a blank line after the
/// summary and the closing quotes on their own line.
fn docstring(w: &mut Py, lines: &[String]) {
    match lines {
        [] => {}
        [only] => w.line(format!("\"\"\"{only}\"\"\"")),
        [first, rest @ ..] => {
            w.line(format!("\"\"\"{first}"));
            w.blank();
            for line in rest {
                w.line(line.as_str());
            }
            w.line("\"\"\"");
        }
    }
}

fn enum_def(w: &mut Py, schema: &Schema, e: &Enum) {
    let name = class_name(schema, &e.package, &e.name);
    w.open(format!("class {name}(int):"));
    let mut docs = e.docs.clone();
    docs.push("Open enum: values outside the schema are preserved.".to_string());
    docstring(w, &docs);
    w.blank();
    let labels: Vec<String> = e
        .variants
        .iter()
        .map(|v| format!("{}: \"{}\"", v.value, v.name))
        .collect();
    w.line(format!("_LABELS = {{{}}}", labels.join(", ")));
    w.blank();
    w.open("def label(self):");
    w.line("\"\"\"Schema name of the value, if it has one.\"\"\"");
    w.line(format!("return {name}._LABELS.get(int(self))"));
    w.end();
    w.end();
    w.blank();
    w.blank();
    for v in &e.variants {
        for doc in &v.docs {
            w.line(format!("# {doc}"));
        }
        w.line(format!("{name}.{} = {name}({})", shout(&v.name), v.value));
    }
}

fn message_def(w: &mut Py, schema: &Schema, m: &Message) {
    let name = class_name(schema, &m.package, &m.name);
    let view_name = format!("{name}View");

    // Owned class.
    w.open(format!("class {name}:"));
    docstring(w, &m.docs);
    if !m.docs.is_empty() {
        w.blank();
    }
    if m.fields.is_empty() {
        w.line("__slots__ = ()");
    } else {
        w.open("__slots__ = (");
        for f in &m.fields {
            w.line(format!("\"{}\",", python_ident(&f.name)));
        }
        w.end();
        w.line(")");
    }
    w.blank();
    w.line(format!("_FIXED_LEN = {}", m.fixed_len));

    if !m.fields.is_empty() {
        w.blank();
        w.open("def __init__(");
        w.line("self,");
        w.line("*,");
        for f in &m.fields {
            w.line(format!(
                "{}={},",
                python_ident(&f.name),
                default_expr(schema, f)
            ));
        }
        w.end();
        w.open("):");
        for f in &m.fields {
            let field = python_ident(&f.name);
            if matches!(f.ty, Type::List(_)) {
                w.line(format!("self.{field} = [] if {field} is None else {field}"));
            } else {
                w.line(format!("self.{field} = {field}"));
            }
        }
        w.end();
    }

    w.blank();
    w.open("def __eq__(self, other):");
    w.open(format!("if not isinstance(other, {name}):"));
    w.line("return NotImplemented");
    w.end();
    w.open("return all(");
    w.line("getattr(self, name) == getattr(other, name) for name in self.__slots__");
    w.end();
    w.line(")");
    w.end();

    w.blank();
    w.open("def __repr__(self):");
    w.open("fields = \", \".join(");
    w.line("f\"{name}={getattr(self, name)!r}\" for name in self.__slots__");
    w.end();
    w.line(")");
    w.line(format!("return f\"{name}({{fields}})\""));
    w.end();

    w.blank();
    w.open("def encode(self):");
    w.line("w = nanobuf.Writer()");
    w.line("self._write(w)");
    w.line("return w.finish()");
    w.end();

    w.blank();
    w.line("@classmethod");
    w.open("def decode(cls, data):");
    w.line(format!("return {view_name}(data).to_owned()"));
    w.end();

    w.blank();
    w.open("def _write(self, w):");
    w.line("w.begin(self._FIXED_LEN)");
    for f in &m.fields {
        write_field(w, schema, f);
    }
    w.end();

    proto_codecs(w, schema, m);
    w.end();
    w.blank();
    w.blank();

    // Zero-copy view.
    w.open(format!("class {view_name}:"));
    w.line(format!("\"\"\"Zero-copy reader for {name}.\"\"\""));
    w.blank();
    w.line("__slots__ = (\"_view\",)");
    w.blank();
    w.open("def __init__(self, data):");
    w.open("if not isinstance(data, nanobuf.View):");
    w.line("data = nanobuf.View.parse(data)");
    w.end();
    w.line("self._view = data");
    w.end();
    w.blank();
    w.line("@property");
    w.open("def data(self):");
    w.line("\"\"\"Raw message bytes, for forwarding without re-encoding.\"\"\"");
    w.line("return self._view.data");
    w.end();
    for f in &m.fields {
        w.blank();
        view_accessor(w, schema, f);
    }
    w.blank();
    to_owned(w, m, &name);
    w.end();
}

/// Emits the `_write` statements for one field.
fn write_field(w: &mut Py, schema: &Schema, f: &Field) {
    let field = format!("self.{}", python_ident(&f.name));
    match (f.layout.data, f.ty) {
        (DataSlot::Bit(bit), _) => {
            if let Some(p) = f.layout.presence {
                w.open(format!("if {field} is not None:"));
                w.line(format!("w.put_bit({}, {}, True)", p.byte, p.bit));
                w.line(format!("w.put_bit({}, {}, {field})", bit.byte, bit.bit));
                w.end();
            } else {
                w.line(format!("w.put_bit({}, {}, {field})", bit.byte, bit.bit));
            }
        }
        (DataSlot::Bytes { offset, .. }, ty) => {
            let fmt = match ty {
                Type::Scalar(s) => fmt_char(s),
                Type::Enum(id) => fmt_char(schema.enumeration(id).backing),
                _ => unreachable!("byte slots hold scalars and enums"),
            };
            if let Some(p) = f.layout.presence {
                w.open(format!("if {field} is not None:"));
                w.line(format!("w.put_bit({}, {}, True)", p.byte, p.bit));
                w.line(format!("w.put_scalar({offset}, \"{fmt}\", {field})"));
                w.end();
            } else {
                w.line(format!("w.put_scalar({offset}, \"{fmt}\", {field})"));
            }
        }
        (DataSlot::Offset { offset }, Type::String) => {
            if f.optional {
                w.open(format!("if {field} is not None:"));
                w.line(format!(
                    "w.put_bytes({offset}, {field}.encode(\"utf-8\"), True)"
                ));
                w.end();
            } else {
                w.line(format!(
                    "w.put_bytes({offset}, {field}.encode(\"utf-8\"), False)"
                ));
            }
        }
        (DataSlot::Offset { offset }, Type::Bytes) => {
            if f.optional {
                w.open(format!("if {field} is not None:"));
                w.line(format!("w.put_bytes({offset}, {field}, True)"));
                w.end();
            } else {
                w.line(format!("w.put_bytes({offset}, {field}, False)"));
            }
        }
        (DataSlot::Offset { offset }, Type::Message(_)) => {
            w.open(format!("if {field} is not None:"));
            w.line(format!("w.put_message({offset}, {field}._write)"));
            w.end();
        }
        (DataSlot::Offset { offset }, Type::List(elem)) => match elem {
            ElemType::Scalar(_) | ElemType::Enum(_) => {
                let fmt = elem_fmt(schema, elem);
                w.line(format!("w.put_scalar_list({offset}, \"{fmt}\", {field})"));
            }
            ElemType::String => {
                w.line(format!(
                    "w.put_offset_list({offset}, {field}, lambda w, item: w.heap_bytes(item.encode(\"utf-8\")))"
                ));
            }
            ElemType::Bytes => {
                w.line(format!(
                    "w.put_offset_list({offset}, {field}, lambda w, item: w.heap_bytes(item))"
                ));
            }
            ElemType::Message(_) => {
                w.line(format!(
                    "w.put_offset_list({offset}, {field}, lambda w, item: w.heap_message(item._write))"
                ));
            }
        },
        (slot, ty) => unreachable!("invalid slot {slot:?} for type {ty:?}"),
    }
}

/// Property name for a field accessor on the view, avoiding builtins.
fn accessor_name(f: &Field) -> String {
    let name = python_ident(&f.name);
    if RESERVED_VIEW_ATTRS.contains(&name.as_str()) {
        format!("get_{name}")
    } else {
        name
    }
}

fn view_accessor(w: &mut Py, schema: &Schema, f: &Field) {
    w.line("@property");
    w.open(format!("def {}(self):", accessor_name(f)));
    docstring(w, &f.docs);
    match (f.layout.data, f.ty) {
        (DataSlot::Bit(bit), _) => {
            if let Some(p) = f.layout.presence {
                w.open(format!("if not self._view.bit_at({}, {}):", p.byte, p.bit));
                w.line("return None");
                w.end();
            }
            w.line(format!(
                "return self._view.bit_at({}, {})",
                bit.byte, bit.bit
            ));
        }
        (DataSlot::Bytes { offset, .. }, ty) => {
            let read = match ty {
                Type::Scalar(s) => {
                    format!("self._view.scalar_at({offset}, \"{}\")", fmt_char(s))
                }
                Type::Enum(id) => format!(
                    "{}(self._view.scalar_at({offset}, \"{}\"))",
                    enum_class(schema, id),
                    fmt_char(schema.enumeration(id).backing)
                ),
                _ => unreachable!("byte slots hold scalars and enums"),
            };
            if let Some(p) = f.layout.presence {
                w.open(format!("if not self._view.bit_at({}, {}):", p.byte, p.bit));
                w.line("return None");
                w.end();
            }
            w.line(format!("return {read}"));
        }
        (DataSlot::Offset { offset }, Type::String) => {
            if f.optional {
                w.line(format!("return self._view.str_at({offset})"));
            } else {
                w.line(format!("value = self._view.str_at({offset})"));
                w.line("return \"\" if value is None else value");
            }
        }
        (DataSlot::Offset { offset }, Type::Bytes) => {
            if f.optional {
                w.line(format!("return self._view.bytes_at({offset})"));
            } else {
                w.line(format!("value = self._view.bytes_at({offset})"));
                w.line("return b\"\" if value is None else value");
            }
        }
        (DataSlot::Offset { offset }, Type::Message(id)) => {
            w.line(format!("view = self._view.message_at({offset})"));
            w.line(format!(
                "return None if view is None else {}View(view)",
                message_class(schema, id)
            ));
        }
        (DataSlot::Offset { offset }, Type::List(elem)) => match elem {
            ElemType::Scalar(s) => {
                w.line(format!(
                    "return self._view.scalar_list_at({offset}, \"{}\")",
                    fmt_char(s)
                ));
            }
            ElemType::Enum(id) => {
                w.line(format!(
                    "return self._view.scalar_list_at({offset}, \"{}\", {})",
                    fmt_char(schema.enumeration(id).backing),
                    enum_class(schema, id)
                ));
            }
            ElemType::String => {
                w.line(format!(
                    "return nanobuf.StrList(self._view.offset_list_at({offset}))"
                ));
            }
            ElemType::Bytes => {
                w.line(format!(
                    "return nanobuf.BytesList(self._view.offset_list_at({offset}))"
                ));
            }
            ElemType::Message(id) => {
                w.line(format!(
                    "return nanobuf.MessageList(self._view.offset_list_at({offset}), {}View)",
                    message_class(schema, id)
                ));
            }
        },
        (slot, ty) => unreachable!("invalid slot {slot:?} for type {ty:?}"),
    }
    w.end();
}

fn to_owned(w: &mut Py, m: &Message, name: &str) {
    w.open("def to_owned(self):");
    w.line(format!(
        "\"\"\"Copies every field into an owned {name}.\"\"\""
    ));
    if m.fields.is_empty() {
        w.line(format!("return {name}()"));
        w.end();
        return;
    }
    // Message-typed fields are read once and checked for absence.
    for f in &m.fields {
        if matches!(f.ty, Type::Message(_)) {
            w.line(format!(
                "{} = self.{}",
                python_ident(&f.name),
                accessor_name(f)
            ));
        }
    }
    w.open(format!("return {name}("));
    for f in &m.fields {
        let field = python_ident(&f.name);
        let method = accessor_name(f);
        let expr = match f.ty {
            Type::Scalar(_) | Type::Enum(_) | Type::String | Type::Bytes => {
                format!("self.{method}")
            }
            Type::Message(_) => format!("None if {field} is None else {field}.to_owned()"),
            Type::List(ElemType::Message(_)) => {
                format!("[item.to_owned() for item in self.{method}]")
            }
            Type::List(_) => format!("self.{method}.to_list()"),
        };
        w.line(format!("{field}={expr},"));
    }
    w.end();
    w.line(")");
    w.end();
}

/// Proto3 migration codecs on the owned class.
fn proto_codecs(w: &mut Py, schema: &Schema, m: &Message) {
    w.blank();
    w.open("def encode_proto3(self):");
    w.line("\"\"\"Encodes to the proto3 wire format (migration mode only).\"\"\"");
    w.line("out = bytearray()");
    w.line("self._write_proto3(out)");
    w.line("return bytes(out)");
    w.end();

    w.blank();
    w.open("def _write_proto3(self, out):");
    if m.fields.is_empty() {
        w.line("pass");
    }
    for f in &m.fields {
        proto_write_field(w, f);
    }
    w.end();

    w.blank();
    w.line("@classmethod");
    w.open("def decode_proto3(cls, data):");
    w.line("\"\"\"Decodes the proto3 wire format (migration mode only).\"\"\"");
    if m.fields.is_empty() {
        w.open("for _ in nanobuf.FieldReader(data):");
        w.line("pass");
        w.end();
        w.line("return cls()");
        w.end();
        return;
    }
    w.line("message = cls()");
    // Unknown fields fall through the chain and are skipped.
    w.open("for field, wire_type, value in nanobuf.FieldReader(data):");
    for (i, f) in m.fields.iter().enumerate() {
        proto_read_field(w, schema, f, i == 0);
    }
    w.end();
    w.line("return message");
    w.end();
}

/// Expression converting `value` of the field's Python type to the u64 the
/// varint writer takes (it sign-extends negatives itself).
fn varint_encode_expr(s: ScalarType, enc: ProtoEncoding, value: &str) -> String {
    match (enc, s) {
        (_, ScalarType::Bool) => format!("int({value})"),
        (ProtoEncoding::ZigZag, _) => format!("nanobuf.zigzag_encode({value})"),
        _ => value.to_string(),
    }
}

/// Expression converting a raw varint `v` into the field's Python value,
/// truncating to the scalar's width exactly like the Rust `as` casts.
fn varint_decode_expr(s: ScalarType, enc: ProtoEncoding, v: &str) -> String {
    if s == ScalarType::Bool {
        return format!("{v} != 0");
    }
    let bits = s.size() * 8;
    if enc == ProtoEncoding::ZigZag {
        let decoded = format!("nanobuf.zigzag_decode({v})");
        if bits < 64 {
            return format!("nanobuf.to_signed({decoded}, {bits})");
        }
        return decoded;
    }
    if s.is_signed() {
        format!("nanobuf.to_signed({v}, {bits})")
    } else if bits < 64 {
        format!("{v} & 0x{:X}", (1u64 << bits) - 1)
    } else {
        v.to_string()
    }
}

fn proto_write_field(w: &mut Py, f: &Field) {
    let field = format!("self.{}", python_ident(&f.name));
    let id = f.id;
    match f.ty {
        Type::Scalar(s) => {
            if f.optional {
                w.open(format!("if {field} is not None:"));
            } else if s == ScalarType::Bool {
                w.open(format!("if {field}:"));
            } else if s.is_float() {
                w.open(format!("if {} != 0.0:", proto_value_expr(s, &field)));
            } else {
                w.open(format!("if {field} != 0:"));
            }
            if f.proto == ProtoEncoding::Fixed {
                w.line(format!(
                    "nanobuf.write_fixed_field(out, {id}, \"{}\", {})",
                    proto_fmt_char(s),
                    proto_value_expr(s, &field)
                ));
            } else {
                w.line(format!(
                    "nanobuf.write_varint_field(out, {id}, {})",
                    varint_encode_expr(s, f.proto, &field)
                ));
            }
            w.end();
        }
        Type::Enum(_) => {
            if f.optional {
                w.open(format!("if {field} is not None:"));
            } else {
                w.open(format!("if {field} != 0:"));
            }
            w.line(format!("nanobuf.write_varint_field(out, {id}, {field})"));
            w.end();
        }
        Type::String => {
            if f.optional {
                w.open(format!("if {field} is not None:"));
            } else {
                w.open(format!("if {field}:"));
            }
            w.line(format!(
                "nanobuf.write_len_field(out, {id}, {field}.encode(\"utf-8\"))"
            ));
            w.end();
        }
        Type::Bytes => {
            if f.optional {
                w.open(format!("if {field} is not None:"));
            } else {
                w.open(format!("if {field}:"));
            }
            w.line(format!("nanobuf.write_len_field(out, {id}, {field})"));
            w.end();
        }
        Type::Message(_) => {
            w.open(format!("if {field} is not None:"));
            w.line(format!(
                "nanobuf.write_len_field(out, {id}, {field}.encode_proto3())"
            ));
            w.end();
        }
        Type::List(elem) => match elem {
            ElemType::Scalar(s) => {
                let item = match (f.proto, s) {
                    (ProtoEncoding::Fixed, _) => format!(
                        "nanobuf.write_fixed(packed, \"{}\", {})",
                        proto_fmt_char(s),
                        proto_value_expr(s, "item")
                    ),
                    _ => format!(
                        "nanobuf.write_varint(packed, {})",
                        varint_encode_expr(s, f.proto, "item")
                    ),
                };
                packed_list(w, id, &field, &item);
            }
            ElemType::Enum(_) => {
                packed_list(w, id, &field, "nanobuf.write_varint(packed, item)");
            }
            ElemType::String => {
                w.open(format!("for item in {field}:"));
                w.line(format!(
                    "nanobuf.write_len_field(out, {id}, item.encode(\"utf-8\"))"
                ));
                w.end();
            }
            ElemType::Bytes => {
                w.open(format!("for item in {field}:"));
                w.line(format!("nanobuf.write_len_field(out, {id}, item)"));
                w.end();
            }
            ElemType::Message(_) => {
                w.open(format!("for item in {field}:"));
                w.line(format!(
                    "nanobuf.write_len_field(out, {id}, item.encode_proto3())"
                ));
                w.end();
            }
        },
    }
}

/// Emits one packed scalar list field, skipped when empty.
fn packed_list(w: &mut Py, id: u32, field: &str, item_stmt: &str) {
    w.open(format!("if {field}:"));
    w.line("packed = bytearray()");
    w.open(format!("for item in {field}:"));
    w.line(item_stmt);
    w.end();
    w.line(format!("nanobuf.write_len_field(out, {id}, packed)"));
    w.end();
}

fn proto_read_field(w: &mut Py, schema: &Schema, f: &Field, first: bool) {
    let target = format!("message.{}", python_ident(&f.name));
    let keyword = if first { "if" } else { "elif" };
    w.open(format!("{keyword} field == {}:", f.id));
    match f.ty {
        Type::Scalar(s) => {
            let expr = if f.proto == ProtoEncoding::Fixed {
                proto_value_expr(
                    s,
                    &format!(
                        "nanobuf.expect_fixed(wire_type, value, \"{}\")",
                        proto_fmt_char(s)
                    ),
                )
            } else {
                varint_decode_expr(s, f.proto, "nanobuf.expect_varint(wire_type, value)")
            };
            w.line(format!("{target} = {expr}"));
        }
        Type::Enum(id) => {
            let backing = schema.enumeration(id).backing;
            let raw = varint_decode_expr(
                backing,
                ProtoEncoding::Varint,
                "nanobuf.expect_varint(wire_type, value)",
            );
            w.line(format!("{target} = {}({raw})", enum_class(schema, id)));
        }
        Type::String => {
            w.line(format!(
                "{target} = nanobuf.expect_string(wire_type, value)"
            ));
        }
        Type::Bytes => {
            w.line(format!(
                "{target} = bytes(nanobuf.expect_len(wire_type, value))"
            ));
        }
        Type::Message(id) => {
            w.line(format!(
                "{target} = {}.decode_proto3(nanobuf.expect_len(wire_type, value))",
                message_class(schema, id)
            ));
        }
        Type::List(elem) => match elem {
            ElemType::Scalar(s) if f.proto == ProtoEncoding::Fixed => {
                let items = format!(
                    "nanobuf.read_packed_fixed(wire_type, value, \"{}\")",
                    proto_fmt_char(s)
                );
                if s == ScalarType::F16 {
                    w.line(format!(
                        "{target}.extend(nanobuf.half_round(v) for v in {items})"
                    ));
                } else {
                    w.line(format!("{target}.extend({items})"));
                }
            }
            ElemType::Scalar(s) => {
                let expr = varint_decode_expr(s, f.proto, "v");
                if expr == "v" {
                    w.line(format!(
                        "{target}.extend(nanobuf.read_packed_varints(wire_type, value))"
                    ));
                } else {
                    w.line("items = nanobuf.read_packed_varints(wire_type, value)");
                    w.line(format!("{target}.extend({expr} for v in items)"));
                }
            }
            ElemType::Enum(id) => {
                let backing = schema.enumeration(id).backing;
                let raw = varint_decode_expr(backing, ProtoEncoding::Varint, "v");
                w.line("items = nanobuf.read_packed_varints(wire_type, value)");
                w.line(format!(
                    "{target}.extend({}({raw}) for v in items)",
                    enum_class(schema, id)
                ));
            }
            ElemType::String => {
                w.line(format!(
                    "{target}.append(nanobuf.expect_string(wire_type, value))"
                ));
            }
            ElemType::Bytes => {
                w.line(format!(
                    "{target}.append(bytes(nanobuf.expect_len(wire_type, value)))"
                ));
            }
            ElemType::Message(id) => {
                w.line(format!(
                    "{target}.append({}.decode_proto3(nanobuf.expect_len(wire_type, value)))",
                    message_class(schema, id)
                ));
            }
        },
    }
    w.end();
}
