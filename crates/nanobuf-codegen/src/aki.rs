//! aki code generator. See `cpp.rs` for the reference C++ backend.
//!
//! Emits one aki module per package on top of the `nanobuf` aki runtime
//! (`runtimes/aki`). Every message gets an owned struct (`Packet`), a
//! zero-copy view (`PacketView<'a>`), a view list for message-typed lists
//! (`PacketViewList<'a>`), and proto3 migration codecs. Structs are declared
//! before any method is defined, so declaration order does not matter, and
//! cross-package references go through the package's module name.

use nanobuf_schema::{
    DataSlot, ElemType, Enum, EnumId, Field, Message, MessageId, ProtoEncoding, ScalarType, Schema,
    Type,
};

use crate::names::{aki_ident, aki_module, pascal, snake};
use crate::writer::CodeWriter;

/// View methods that field accessors must not shadow.
const RESERVED_VIEW_METHODS: &[&str] = &["data", "size", "parse", "to_owned", "view"];

/// Runtime names a generated module may import. Each is imported only when
/// the generated text mentions it, so the module has no unused imports.
const RUNTIME_IMPORTS: &[(&str, &[&str])] = &[
    ("nanobuf::error", &["DecodeError"]),
    ("nanobuf::view", &["View", "OffsetList", "ScalarList"]),
    (
        "nanobuf::scalar",
        &[
            "Float16",
            "read_bool",
            "read_u8",
            "read_u16",
            "read_u32",
            "read_u64",
            "read_i8",
            "read_i16",
            "read_i32",
            "read_i64",
            "read_f16",
            "read_f32",
            "read_f64",
        ],
    ),
    ("nanobuf::writer", &["Writer"]),
    (
        "nanobuf::proto",
        &[
            "FieldReader",
            "WireType",
            "expect_bytes",
            "expect_i32",
            "expect_i64",
            "expect_len",
            "expect_string",
            "expect_varint",
            "read_packed_fixed32",
            "read_packed_fixed64",
            "read_packed_varints",
            "write_fixed",
            "write_fixed_field",
            "write_len_field",
            "write_tag",
            "write_varint",
            "write_varint_field",
            "zigzag_decode",
            "zigzag_encode",
        ],
    ),
    (
        "nanobuf::equal",
        &[
            "same_items",
            "same_byte_lists",
            "same_bytes_opt",
            "same_boxed",
        ],
    ),
    ("akikit::containers::list", &["List", "to_list"]),
    ("akikit::strings::string", &["String", "from_str"]),
    ("akikit::memory::box", &["Box"]),
];

/// Generates the aki module for one package, `package`.
pub fn generate(schema: &Schema, package: &str) -> String {
    let mut body = CodeWriter::new("  ");
    body_of_package(&mut body, schema, package);
    let body = collapse_blank_lines(&body.finish());

    let mut out = CodeWriter::new("  ");
    out.line("// @generated by nanoc. DO NOT EDIT.");
    out.line("// Wire layout is fixed by the schema; see docs/wire-format.md.");
    out.line("//");
    out.line("// View accessors for heap fields distinguish corrupt buffers from");
    out.line("// absent fields:");
    out.line("//   - a non-optional string, bytes, or list reads as empty when absent");
    out.line("//   - an optional one is none when absent and an error when corrupt");
    out.line("//   - a message field is none when absent and an error when corrupt");
    out.line(format!("module {};", aki_module(package)));
    out.blank();
    for line in import_lines(schema, package, &body) {
        out.line(line);
    }
    let mut text = out.finish();
    text.push('\n');
    text.push_str(&body);
    text
}

fn body_of_package(w: &mut CodeWriter, schema: &Schema, package: &str) {
    for e in schema.enums.iter().filter(|e| e.package == package) {
        w.blank();
        enum_def(w, e);
    }
    let ids: Vec<MessageId> = schema
        .message_order()
        .into_iter()
        .filter(|&id| schema.message(id).package == package)
        .collect();
    for &id in &ids {
        let m = schema.message(id);
        w.blank();
        owned_struct(w, schema, m);
        w.blank();
        view_struct(w, schema, m);
        w.blank();
        view_list_struct(w, m);
    }
    for &id in &ids {
        let m = schema.message(id);
        w.blank();
        message_impl(w, schema, m);
    }
}

/// Joins runs of blank lines into one, so sections separated by `blank`
/// calls do not stack. The aki formatter writes exactly this form.
fn collapse_blank_lines(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut previous_blank = true;
    for line in text.lines() {
        let blank = line.trim().is_empty();
        if blank && previous_blank {
            continue;
        }
        out.push_str(line);
        out.push('\n');
        previous_blank = blank;
    }
    while out.ends_with("\n\n") {
        out.pop();
    }
    out
}

/// `import` lines for the runtime and for other packages that the body uses.
fn import_lines(schema: &Schema, package: &str, body: &str) -> Vec<String> {
    let mut lines = Vec::new();
    for (module, names) in RUNTIME_IMPORTS {
        let used: Vec<&str> = names
            .iter()
            .copied()
            .filter(|name| mentions(body, name))
            .collect();
        if used.is_empty() {
            continue;
        }
        lines.push(format!("import {{{}}} from {module};", used.join(", ")));
    }
    if body.contains("") {
        lines.push("import nanobuf::proto;".to_string());
    }
    for other in schema.packages() {
        if other == package {
            continue;
        }
        let module = aki_module(other);
        if body.contains(&format!("{module}::")) {
            lines.push(format!("import {module};"));
        }
    }
    lines
}

/// True when `name` occurs in `text` as a whole identifier that is not a
/// method call (`x.name`), so a method that shares a free function's name
/// does not count as a use of that function.
fn mentions(text: &str, name: &str) -> bool {
    let bytes = text.as_bytes();
    let mut from = 0;
    while let Some(at) = text[from..].find(name) {
        let start = from + at;
        let end = start + name.len();
        let before_ok =
            start == 0 || (!is_ident_byte(bytes[start - 1]) && bytes[start - 1] != b'.');
        let after_ok = end >= bytes.len() || !is_ident_byte(bytes[end]);
        if before_ok && after_ok {
            return true;
        }
        from = end;
    }
    false
}

fn is_ident_byte(b: u8) -> bool {
    b.is_ascii_alphanumeric() || b == b'_'
}

fn aki_scalar(s: ScalarType) -> &'static str {
    match s {
        ScalarType::Bool => "bool",
        ScalarType::U8 => "u8",
        ScalarType::U16 => "u16",
        ScalarType::U32 => "u32",
        ScalarType::U64 => "u64",
        ScalarType::I8 => "i8",
        ScalarType::I16 => "i16",
        ScalarType::I32 => "i32",
        ScalarType::I64 => "i64",
        ScalarType::F16 => "Float16",
        ScalarType::F32 => "f32",
        ScalarType::F64 => "f64",
    }
}

/// Unsigned integer type of the same width as a scalar, for bit casts.
fn unsigned_of(s: ScalarType) -> &'static str {
    match s.size() {
        1 => "u8",
        2 => "u16",
        4 => "u32",
        _ => "u64",
    }
}

/// Bytes one element of a scalar list occupies. A bool is bit-packed in a
/// fixed section, but a list element is one byte, as in the C++ backend.
fn element_size(s: ScalarType) -> u32 {
    match s {
        ScalarType::Bool => 1,
        _ => s.size(),
    }
}

/// Mask that keeps the low bits of a raw wire value, as C++ truncation does.
fn mask_of(s: ScalarType) -> Option<&'static str> {
    match s.size() {
        1 => Some("0xff"),
        2 => Some("0xffff"),
        4 => Some("0xffffffff"),
        _ => None,
    }
}

/// Name of a message or enum type as seen from `current`'s module.
fn type_ref(current: &Message, package: &str, name: &str) -> String {
    let name = pascal(name);
    if package == current.package {
        name
    } else {
        format!("{}::{name}", aki_module(package))
    }
}

fn message_ref(schema: &Schema, current: &Message, id: MessageId) -> String {
    let target = schema.message(id);
    type_ref(current, &target.package, &target.name)
}

fn view_ref(schema: &Schema, current: &Message, id: MessageId) -> String {
    let target = schema.message(id);
    type_ref(
        current,
        &target.package,
        &format!("{}View", pascal(&target.name)),
    )
}

fn view_list_ref(schema: &Schema, current: &Message, id: MessageId) -> String {
    let target = schema.message(id);
    type_ref(
        current,
        &target.package,
        &format!("{}ViewList", pascal(&target.name)),
    )
}

fn enum_ref(schema: &Schema, current: &Message, id: EnumId) -> String {
    let target = schema.enumeration(id);
    type_ref(current, &target.package, &target.name)
}

/// Reader for one element of a scalar list, given its enum or scalar type.
fn element_reader(s: ScalarType) -> String {
    format!("read_{}", s.name())
}

fn enum_reader(e: &Enum) -> String {
    format!("read_{}_value", snake(&e.name))
}

fn enum_def(w: &mut CodeWriter, e: &Enum) {
    let name = pascal(&e.name);
    w.doc(&e.docs, "///");
    w.open(format!("pub open enum {name} as {} {{", e.backing.name()));
    for v in &e.variants {
        w.doc(&v.docs, "///");
        w.line(format!("{} = {},", pascal(&v.name), v.value));
    }
    w.close("}");
    w.blank();
    w.line("/// Schema name of a value, or none if it has none.");
    w.open(format!(
        "pub fn {}_name(value: {name}): str? => match (value) {{",
        snake(&e.name)
    ));
    for v in &e.variants {
        w.line(format!("{name}::{} => \"{}\",", pascal(&v.name), v.name));
    }
    w.line("_ => none,");
    w.close("};");
    w.blank();
    w.line(format!("/// Decodes one element of a `list<{}>`.", e.name));
    w.line(format!(
        "pub fn {}(b: &[u8]): {name} => {}(b) as {name};",
        enum_reader(e),
        element_reader(e.backing)
    ));
}

/// Owned value type of a field, as the struct declares it.
fn owned_type(schema: &Schema, m: &Message, f: &Field) -> String {
    let base = match f.ty {
        Type::Scalar(s) => aki_scalar(s).to_string(),
        Type::Enum(id) => enum_ref(schema, m, id),
        Type::String => "String".to_string(),
        Type::Bytes => "List<u8>".to_string(),
        Type::Message(id) => {
            let path = message_ref(schema, m, id);
            return if f.boxed {
                format!("Box<{path}>?")
            } else {
                format!("{path}?")
            };
        }
        Type::List(elem) => return format!("List<{}>", elem_owned(schema, m, elem)),
    };
    if f.optional { format!("{base}?") } else { base }
}

fn elem_owned(schema: &Schema, m: &Message, elem: ElemType) -> String {
    match elem {
        ElemType::Scalar(s) => aki_scalar(s).to_string(),
        ElemType::Enum(id) => enum_ref(schema, m, id),
        ElemType::String => "String".to_string(),
        ElemType::Bytes => "List<u8>".to_string(),
        ElemType::Message(id) => message_ref(schema, m, id),
    }
}

/// Initial value of an owned field, so `T {}` builds a default message.
fn owned_default(schema: &Schema, m: &Message, f: &Field) -> String {
    if f.optional {
        return "none".to_string();
    }
    match f.ty {
        Type::Scalar(ScalarType::Bool) => "false".to_string(),
        Type::Scalar(ScalarType::F16) => "Float16 {}".to_string(),
        Type::Scalar(ScalarType::F32 | ScalarType::F64) => "0.0".to_string(),
        Type::Scalar(_) => "0".to_string(),
        Type::Enum(id) => format!("0 as {}", enum_ref(schema, m, id)),
        Type::String => "String()".to_string(),
        Type::Bytes => "List::<u8>()".to_string(),
        Type::Message(_) => "none".to_string(),
        Type::List(elem) => format!("List::<{}>()", elem_owned(schema, m, elem)),
    }
}

fn owned_struct(w: &mut CodeWriter, schema: &Schema, m: &Message) {
    let name = pascal(&m.name);
    w.doc(&m.docs, "///");
    w.open(format!("pub struct {name} : Equal {{"));
    for f in &m.fields {
        w.doc(&f.docs, "///");
        w.line(format!(
            "pub var {}: {} = {};",
            aki_ident(&f.name),
            owned_type(schema, m, f),
            owned_default(schema, m, f)
        ));
    }
    if !m.fields.is_empty() {
        w.blank();
    }
    w.line("pub fn fixed_len(): u16;");
    w.line(format!("pub fn eq(self&, other&: {name}): bool;"));
    w.line("pub fn encode(self&): List<u8>;");
    w.line("pub fn encode_proto3(self&): List<u8>;");
    w.line("// Internal: serializes into an in-progress message buffer.");
    w.line("pub fn write_to(self&, var w&: Writer);");
    w.line("// Internal: appends proto3-encoded fields to `out`.");
    w.line("pub fn write_proto3_to(self&, var out&: List<u8>);");
    w.line(format!("pub fn decode(data: &[u8]): {name} ! DecodeError;"));
    w.line(format!(
        "pub fn decode_proto3(data: &[u8]): {name} ! DecodeError;"
    ));
    w.close("}");
}

/// Expression for a scalar's bits as the u64 the wire writer takes.
fn raw_bits(s: ScalarType, e: &str) -> String {
    match s {
        ScalarType::Bool | ScalarType::U8 | ScalarType::U16 | ScalarType::U32 | ScalarType::U64 => {
            format!("({e}) as u64")
        }
        ScalarType::I8 | ScalarType::I16 | ScalarType::I32 => {
            format!("@bit_cast({}, {e}) as u64", unsigned_of(s))
        }
        ScalarType::I64 => format!("@bit_cast(u64, {e})"),
        ScalarType::F16 => format!("({e}).bits as u64"),
        ScalarType::F32 => format!("@bit_cast(u32, {e}) as u64"),
        ScalarType::F64 => format!("@bit_cast(u64, {e})"),
    }
}

/// Bits of an enum value, through its backing type.
fn raw_enum_bits(backing: ScalarType, e: &str) -> String {
    raw_bits(backing, &format!("({e}) as {}", aki_scalar(backing)))
}

/// Wire value of a proto3 scalar under its encoding.
fn proto_encode_scalar(s: ScalarType, enc: ProtoEncoding, e: &str) -> String {
    match (s, enc) {
        (ScalarType::Bool, _) => raw_bits(s, e),
        // f16 travels widened to float (fixed32) on the proto3 wire.
        (ScalarType::F16, ProtoEncoding::Fixed) => {
            format!("@bit_cast(u32, ({e}).to_f32()) as u64")
        }
        (_, ProtoEncoding::Fixed) => raw_bits(s, e),
        (_, ProtoEncoding::ZigZag) => format!("zigzag_encode(({e}) as i64)"),
        (_, ProtoEncoding::Varint | ProtoEncoding::LengthDelimited) => {
            if s.is_signed() {
                // Signed varints sign-extend through i64.
                format!("@bit_cast(u64, ({e}) as i64)")
            } else if s.is_float() {
                raw_bits(s, e)
            } else {
                format!("({e}) as u64")
            }
        }
    }
}

/// Wire value of a proto3 enum, which always uses a sign-extended varint.
fn proto_encode_enum(backing: ScalarType, e: &str) -> String {
    format!("@bit_cast(u64, (({e}) as {}) as i64)", aki_scalar(backing))
}

/// Typed value of a proto3 scalar decoded from the u64 `raw`.
fn proto_decode_scalar(s: ScalarType, enc: ProtoEncoding, raw: &str) -> String {
    match (s, enc) {
        (ScalarType::Bool, _) => format!("({raw}) != 0"),
        (ScalarType::F16, ProtoEncoding::Fixed) => {
            format!("Float16::from_f32(@bit_cast(f32, (({raw}) & 0xffffffff) as u32))")
        }
        (ScalarType::F32, _) => format!("@bit_cast(f32, (({raw}) & 0xffffffff) as u32)"),
        (ScalarType::F64, _) => format!("@bit_cast(f64, {raw})"),
        (ScalarType::I64, ProtoEncoding::ZigZag) => format!("zigzag_decode({raw})"),
        (ScalarType::I64, _) => format!("@bit_cast(i64, {raw})"),
        (_, ProtoEncoding::ZigZag) if s.is_signed() => {
            let ty = aki_scalar(s);
            let uty = unsigned_of(s);
            let mask = mask_of(s).unwrap_or("0xffffffffffffffff");
            format!("@bit_cast({ty}, (@bit_cast(u64, zigzag_decode({raw})) & {mask}) as {uty})")
        }
        (ScalarType::U64, _) => raw.to_string(),
        _ if s.is_signed() => {
            let ty = aki_scalar(s);
            let uty = unsigned_of(s);
            let mask = mask_of(s).unwrap_or("0xffffffffffffffff");
            format!("@bit_cast({ty}, (({raw}) & {mask}) as {uty})")
        }
        _ => {
            let uty = aki_scalar(s);
            let mask = mask_of(s).unwrap_or("0xffffffffffffffff");
            format!("(({raw}) & {mask}) as {uty}")
        }
    }
}

/// Typed value of a proto3 enum decoded from the u64 `raw`.
fn proto_decode_enum(schema: &Schema, m: &Message, id: EnumId, raw: &str) -> String {
    let e = schema.enumeration(id);
    let backing = proto_decode_scalar(e.backing, ProtoEncoding::Varint, raw);
    format!("({backing}) as {}", enum_ref(schema, m, id))
}

/// Expression that is true when the non-optional scalar `e` is non-zero.
fn nonzero(s: ScalarType, e: &str) -> String {
    match s {
        ScalarType::Bool => e.to_string(),
        ScalarType::F16 => format!("({e}).to_f32() != 0.0"),
        ScalarType::F32 | ScalarType::F64 => format!("({e}) != 0.0"),
        _ => format!("({e}) != 0"),
    }
}

/// Equality of one owned field, as a condition that is true when they differ.
fn differs(f: &Field) -> String {
    let a = format!("self.{}", aki_ident(&f.name));
    let b = format!("other.{}", aki_ident(&f.name));
    match f.ty {
        Type::Bytes if f.optional => format!("!same_bytes_opt({a}, {b})"),
        Type::Bytes => format!("!same_items({a}.as_slice(), {b}.as_slice())"),
        Type::Message(_) if f.boxed => format!("!same_boxed({a}, {b})"),
        Type::List(ElemType::Bytes) => format!("!same_byte_lists({a}, {b})"),
        Type::List(_) => format!("!same_items({a}.as_slice(), {b}.as_slice())"),
        _ => format!("!({a} == {b})"),
    }
}

fn message_impl(w: &mut CodeWriter, schema: &Schema, m: &Message) {
    let name = pascal(&m.name);
    w.blank();
    w.line(format!("fn {name}::fixed_len(): u16 => {};", m.fixed_len));

    w.blank();
    w.open(format!("fn {name}::eq(self&, other&: {name}): bool {{"));
    for f in &m.fields {
        w.open(format!("if ({}) {{", differs(f)));
        w.line("return false;");
        w.close("}");
    }
    w.line("return true;");
    w.close("}");

    w.blank();
    w.open(format!("fn {name}::encode(self&): List<u8> {{"));
    w.line("var w = Writer {};");
    w.line("self.write_to(w);");
    w.line("return w.into_list();");
    w.close("}");

    w.blank();
    w.open(format!("fn {name}::encode_proto3(self&): List<u8> {{"));
    w.line("var out = List::<u8>();");
    w.line("self.write_proto3_to(out);");
    w.line("return out;");
    w.close("}");

    w.blank();
    w.open(format!("fn {name}::write_to(self&, var w&: Writer) {{"));
    w.line(format!("w.begin({});", m.fixed_len));
    for f in &m.fields {
        write_field(w, schema, f);
    }
    w.close("}");

    proto_codecs(w, schema, m, &name);

    w.blank();
    w.open(format!(
        "fn {name}::decode(data: &[u8]): {name} ! DecodeError {{"
    ));
    w.line(format!("let view = try {name}View::parse(data);"));
    w.line("let owned = try view.to_owned();");
    w.line("return owned;");
    w.close("}");

    w.blank();
    to_owned_and_view_methods(w, schema, m, &name);
}

/// Emits the `WriteTo` statements for one field.
fn write_field(w: &mut CodeWriter, schema: &Schema, f: &Field) {
    let field = format!("self.{}", aki_ident(&f.name));
    match (f.layout.data, f.ty) {
        (DataSlot::Bit(bit), _) => {
            if let Some(p) = f.layout.presence {
                w.open(format!("if (let v = {field}) {{"));
                w.line(format!("w.put_bit({}, {}, true);", p.byte, p.bit));
                w.line(format!("w.put_bit({}, {}, v);", bit.byte, bit.bit));
                w.close("}");
            } else {
                w.line(format!("w.put_bit({}, {}, {field});", bit.byte, bit.bit));
            }
        }
        (DataSlot::Bytes { offset, .. }, ty) => {
            // The value's own type decides its width and its bit pattern.
            let (scalar, enum_backing) = match ty {
                Type::Scalar(s) => (s, None),
                Type::Enum(id) => {
                    let backing = schema.enumeration(id).backing;
                    (backing, Some(backing))
                }
                _ => unreachable!("byte slots hold scalars and enums"),
            };
            let size = scalar.size();
            let bits = |e: &str| match enum_backing {
                Some(backing) => raw_enum_bits(backing, e),
                None => raw_bits(scalar, e),
            };
            if let Some(p) = f.layout.presence {
                w.open(format!("if (let v = {field}) {{"));
                w.line(format!("w.put_bit({}, {}, true);", p.byte, p.bit));
                w.line(format!("w.put_uint({offset}, {}, {size});", bits("v")));
                w.close("}");
            } else {
                w.line(format!("w.put_uint({offset}, {}, {size});", bits(&field)));
            }
        }
        (DataSlot::Offset { offset }, Type::String) => {
            let payload = format!("{field}.as_bytes() as &[u8]");
            if f.optional {
                w.open(format!("if (let s& = {field}) {{"));
                w.line(format!(
                    "w.put_bytes({offset}, s.as_bytes() as &[u8], true);"
                ));
                w.close("}");
            } else {
                w.line(format!("w.put_bytes({offset}, {payload}, false);"));
            }
        }
        (DataSlot::Offset { offset }, Type::Bytes) => {
            if f.optional {
                w.open(format!("if (let b& = {field}) {{"));
                w.line(format!("w.put_bytes({offset}, b.as_slice(), true);"));
                w.close("}");
            } else {
                w.line(format!("w.put_bytes({offset}, {field}.as_slice(), false);"));
            }
        }
        (DataSlot::Offset { offset }, Type::Message(_)) => {
            w.open(format!("if (let c& = {field}) {{"));
            w.line("let mark = w.open_message();");
            if f.boxed {
                w.line("c.get().write_to(w);");
            } else {
                w.line("c.write_to(w);");
            }
            w.line("let heap = w.close_message(mark);");
            w.line(format!("w.set_slot({offset}, heap);"));
            w.close("}");
        }
        (DataSlot::Offset { offset }, Type::List(elem)) => match elem {
            ElemType::Scalar(_) | ElemType::Enum(_) => {
                let (s, raw) = match elem {
                    ElemType::Scalar(s) => (s, raw_bits(s, &format!("{field}[i]"))),
                    ElemType::Enum(id) => {
                        let backing = schema.enumeration(id).backing;
                        (backing, raw_enum_bits(backing, &format!("{field}[i]")))
                    }
                    _ => unreachable!(),
                };
                let size = element_size(s);
                w.open(format!("if ({field}.len() > 0) {{"));
                w.line(format!(
                    "let entry = w.begin_scalar_list({field}.len(), {size});"
                ));
                w.open(format!("for (let i in 0..{field}.len()) {{"));
                w.line(format!(
                    "w.put_uint(entry as usize + 4 + i * {size}, {raw}, {size});"
                ));
                w.close("}");
                w.line(format!("w.set_slot({offset}, entry);"));
                w.close("}");
            }
            ElemType::String | ElemType::Bytes => {
                let payload = if matches!(elem, ElemType::String) {
                    format!("{field}[i].as_bytes() as &[u8]")
                } else {
                    format!("{field}[i].as_slice()")
                };
                w.open(format!("if ({field}.len() > 0) {{"));
                w.line(format!("let entry = w.begin_offset_list({field}.len());"));
                w.open(format!("for (let i in 0..{field}.len()) {{"));
                w.line(format!("let offset = w.heap_bytes({payload});"));
                w.line("w.put_uint(entry as usize + 4 + i * 4, offset as u64, 4);");
                w.close("}");
                w.line(format!("w.set_slot({offset}, entry);"));
                w.close("}");
            }
            ElemType::Message(_) => {
                w.open(format!("if ({field}.len() > 0) {{"));
                w.line(format!("let entry = w.begin_offset_list({field}.len());"));
                w.open(format!("for (let i in 0..{field}.len()) {{"));
                w.line(format!("let item& = {field}[i];"));
                w.line("let mark = w.open_message();");
                w.line("item.write_to(w);");
                w.line("let offset = w.close_message(mark);");
                w.line("w.put_uint(entry as usize + 4 + i * 4, offset as u64, 4);");
                w.close("}");
                w.line(format!("w.set_slot({offset}, entry);"));
                w.close("}");
            }
        },
        (slot, ty) => unreachable!("invalid slot {slot:?} for type {ty:?}"),
    }
}

/// Proto3 migration codecs.
fn proto_codecs(w: &mut CodeWriter, schema: &Schema, m: &Message, name: &str) {
    w.blank();
    w.open(format!(
        "fn {name}::write_proto3_to(self&, var out&: List<u8>) {{"
    ));
    for f in &m.fields {
        proto_write_field(w, schema, f);
    }
    w.close("}");

    w.blank();
    w.open(format!(
        "fn {name}::decode_proto3(data: &[u8]): {name} ! DecodeError {{"
    ));
    w.line(format!("var message = {name} {{}};"));
    w.line("var reader = FieldReader { buf: data };");
    w.open("while (let field = try reader.next()) {");
    w.open("switch (field.number) {");
    for f in &m.fields {
        proto_read_field(w, schema, m, f);
    }
    w.line("default: {}");
    w.close("}");
    w.close("}");
    w.line("return message;");
    w.close("}");
}

/// Emits the proto3 encoding of one field, skipping default values.
fn proto_write_field(w: &mut CodeWriter, schema: &Schema, f: &Field) {
    let field = format!("self.{}", aki_ident(&f.name));
    let id = f.id;
    match f.ty {
        Type::Scalar(s) => {
            if f.optional {
                w.open(format!("if (let v = {field}) {{"));
                w.line(proto_write_scalar(s, f.proto, id, "v"));
                w.close("}");
            } else {
                w.open(format!("if ({}) {{", nonzero(s, &field)));
                w.line(proto_write_scalar(s, f.proto, id, &field));
                w.close("}");
            }
        }
        Type::Enum(eid) => {
            let backing = schema.enumeration(eid).backing;
            let value = |e: &str| proto_encode_enum(backing, e);
            if f.optional {
                w.open(format!("if (let v = {field}) {{"));
                w.line(format!("write_varint_field(out, {id}, {});", value("v")));
                w.close("}");
            } else {
                w.open(format!("if (({field}) as {} != 0) {{", aki_scalar(backing)));
                w.line(format!("write_varint_field(out, {id}, {});", value(&field)));
                w.close("}");
            }
        }
        Type::String | Type::Bytes => {
            let payload = |e: &str| {
                if matches!(f.ty, Type::String) {
                    format!("{e}.as_bytes() as &[u8]")
                } else {
                    format!("{e}.as_slice()")
                }
            };
            if f.optional {
                w.open(format!("if (let v& = {field}) {{"));
                w.line(format!("write_len_field(out, {id}, {});", payload("v")));
                w.close("}");
            } else {
                w.open(format!("if ({field}.len() > 0) {{"));
                w.line(format!("write_len_field(out, {id}, {});", payload(&field)));
                w.close("}");
            }
        }
        Type::Message(_) => {
            let target = if f.boxed { "v.get()" } else { "v" };
            w.open(format!("if (let v& = {field}) {{"));
            w.line("var nested = List::<u8>();");
            w.line(format!("{target}.write_proto3_to(nested);"));
            w.line(format!("write_len_field(out, {id}, nested.as_slice());"));
            w.close("}");
        }
        Type::List(elem) => {
            w.open(format!("if ({field}.len() > 0) {{"));
            match elem {
                ElemType::Scalar(s) => {
                    w.line("var payload = List::<u8>();");
                    w.open(format!("for (let i in 0..{field}.len()) {{"));
                    w.line(proto_append_scalar(s, f.proto, &format!("{field}[i]")));
                    w.close("}");
                    w.line(format!("write_len_field(out, {id}, payload.as_slice());"));
                }
                ElemType::Enum(eid) => {
                    let backing = schema.enumeration(eid).backing;
                    w.line("var payload = List::<u8>();");
                    w.open(format!("for (let i in 0..{field}.len()) {{"));
                    w.line(format!(
                        "write_varint(payload, {});",
                        proto_encode_enum(backing, &format!("{field}[i]"))
                    ));
                    w.close("}");
                    w.line(format!("write_len_field(out, {id}, payload.as_slice());"));
                }
                ElemType::String | ElemType::Bytes => {
                    let payload = if matches!(elem, ElemType::String) {
                        format!("{field}[i].as_bytes() as &[u8]")
                    } else {
                        format!("{field}[i].as_slice()")
                    };
                    w.open(format!("for (let i in 0..{field}.len()) {{"));
                    w.line(format!("write_len_field(out, {id}, {payload});"));
                    w.close("}");
                }
                ElemType::Message(_) => {
                    w.open(format!("for (let i in 0..{field}.len()) {{"));
                    w.line(format!("let item& = {field}[i];"));
                    w.line("var nested = List::<u8>();");
                    w.line("item.write_proto3_to(nested);");
                    w.line(format!("write_len_field(out, {id}, nested.as_slice());"));
                    w.close("}");
                }
            }
            w.close("}");
        }
    }
}

/// One proto3 field write for a scalar value expression `e`.
fn proto_write_scalar(s: ScalarType, enc: ProtoEncoding, id: u32, e: &str) -> String {
    let value = proto_encode_scalar(s, enc, e);
    match (enc, s.proto_size()) {
        (ProtoEncoding::Fixed, 4) => {
            format!("write_fixed_field(out, {id}, WireType::I32, {value}, 4);")
        }
        (ProtoEncoding::Fixed, _) => {
            format!("write_fixed_field(out, {id}, WireType::I64, {value}, 8);")
        }
        _ => format!("write_varint_field(out, {id}, {value});"),
    }
}

/// One element of a packed scalar list appended to `payload`.
fn proto_append_scalar(s: ScalarType, enc: ProtoEncoding, e: &str) -> String {
    let value = proto_encode_scalar(s, enc, e);
    match (enc, s.proto_size()) {
        (ProtoEncoding::Fixed, 4) => format!("write_fixed(payload, {value}, 4);"),
        (ProtoEncoding::Fixed, _) => format!("write_fixed(payload, {value}, 8);"),
        _ => format!("write_varint(payload, {value});"),
    }
}

/// Reads one proto3 field into `message`, skipping a shape mismatch by failing.
fn proto_read_field(w: &mut CodeWriter, schema: &Schema, m: &Message, f: &Field) {
    let field = aki_ident(&f.name);
    let id = f.id;
    w.open(format!("case {id}: {{"));
    match f.ty {
        Type::Scalar(s) => {
            let expect = match (f.proto, s.proto_size()) {
                (ProtoEncoding::Fixed, 4) => "expect_i32",
                (ProtoEncoding::Fixed, _) => "expect_i64",
                _ => "expect_varint",
            };
            w.line(format!("let raw = try {expect}(field.value);"));
            w.line(format!(
                "message.{field} = {};",
                proto_decode_scalar(s, f.proto, "raw")
            ));
        }
        Type::Enum(eid) => {
            w.line("let raw = try expect_varint(field.value);");
            w.line(format!(
                "message.{field} = {};",
                proto_decode_enum(schema, m, eid, "raw")
            ));
        }
        Type::String => {
            w.line(format!("message.{field} = try expect_string(field.value);"));
        }
        Type::Bytes => {
            w.line(format!("message.{field} = try expect_bytes(field.value);"));
        }
        Type::Message(target) => {
            let path = message_ref(schema, m, target);
            w.line("let payload = try expect_len(field.value);");
            w.line(format!("let child = try {path}::decode_proto3(payload);"));
            if f.boxed {
                w.line(format!("message.{field} = Box::<{path}>(child);"));
            } else {
                w.line(format!("message.{field} = child;"));
            }
        }
        Type::List(elem) => match elem {
            ElemType::Scalar(s) => {
                let (reader, expr) = match (f.proto, s.proto_size()) {
                    (ProtoEncoding::Fixed, 4) => (
                        "read_packed_fixed32",
                        proto_decode_scalar(s, f.proto, "raw"),
                    ),
                    (ProtoEncoding::Fixed, _) => (
                        "read_packed_fixed64",
                        proto_decode_scalar(s, f.proto, "raw"),
                    ),
                    _ => (
                        "read_packed_varints",
                        proto_decode_scalar(s, f.proto, "raw"),
                    ),
                };
                w.line(format!("let raws = try {reader}(field.value);"));
                w.open("for (let raw in raws) {");
                w.line(format!("message.{field}.push({expr});"));
                w.close("}");
            }
            ElemType::Enum(eid) => {
                w.line("let raws = try read_packed_varints(field.value);");
                w.open("for (let raw in raws) {");
                w.line(format!(
                    "message.{field}.push({});",
                    proto_decode_enum(schema, m, eid, "raw")
                ));
                w.close("}");
            }
            ElemType::String => {
                w.line("let item = try expect_string(field.value);");
                w.line(format!("message.{field}.push(item);"));
            }
            ElemType::Bytes => {
                w.line("let item = try expect_bytes(field.value);");
                w.line(format!("message.{field}.push(item);"));
            }
            ElemType::Message(target) => {
                let path = message_ref(schema, m, target);
                w.line("let payload = try expect_len(field.value);");
                w.line(format!("let child = try {path}::decode_proto3(payload);"));
                w.line(format!("message.{field}.push(child);"));
            }
        },
    }
    w.close("}");
}

fn view_struct(w: &mut CodeWriter, schema: &Schema, m: &Message) {
    let name = pascal(&m.name);
    let view = format!("{name}View");
    w.doc(&[format!("Zero-copy reader for {name}.")], "///");
    w.open(format!("pub struct {view}<'a> : Copy {{"));
    w.line("pub let view: View<'a>");
    w.blank();
    w.line(format!(
        "pub fn parse(data: &'a [u8]): {view}<'a> ! DecodeError;"
    ));
    w.line("// Raw message bytes, for forwarding without re-encoding.");
    w.line("pub fn data(self&): &'a [u8] => self.view.data();");
    w.line("pub fn size(self&): usize => self.view.size();");
    for f in &m.fields {
        for doc in &f.docs {
            w.line(format!("/// {doc}"));
        }
        w.line(format!(
            "pub fn {}(self&): {};",
            accessor_name(f),
            accessor_type(schema, m, f)
        ));
    }
    w.blank();
    w.line(format!("// Copies every field into an owned {name}."));
    w.line(format!("pub fn to_owned(self&): {name} ! DecodeError;"));
    w.close("}");
}

fn view_list_struct(w: &mut CodeWriter, m: &Message) {
    let name = pascal(&m.name);
    let list = format!("{name}ViewList");
    let view = format!("{name}View");
    w.doc(&[format!("Zero-copy list of {name} messages.")], "///");
    w.open(format!("pub struct {list}<'a> : Copy {{"));
    w.line("pub let list: OffsetList<'a>");
    w.blank();
    w.line("pub fn len(self&): usize => self.list.len();");
    w.line(format!(
        "pub fn get(self&, i: usize): {view}<'a> ! DecodeError;"
    ));
    w.line(format!(
        "pub fn to_owned(self&): List<{name}> ! DecodeError;"
    ));
    w.close("}");
}

/// Method name of a view accessor, avoiding the view's own methods.
fn accessor_name(f: &Field) -> String {
    let name = aki_ident(&f.name);
    if RESERVED_VIEW_METHODS.contains(&name.as_str()) {
        format!("get_{name}")
    } else {
        name
    }
}

/// Declared return type of a view accessor.
fn accessor_type(schema: &Schema, m: &Message, f: &Field) -> String {
    match f.ty {
        Type::Scalar(s) => {
            if f.optional {
                format!("{}?", aki_scalar(s))
            } else {
                aki_scalar(s).to_string()
            }
        }
        Type::Enum(id) => {
            let base = enum_ref(schema, m, id);
            if f.optional { format!("{base}?") } else { base }
        }
        Type::String => {
            if f.optional {
                "str<'a>? ! DecodeError".to_string()
            } else {
                "str<'a> ! DecodeError".to_string()
            }
        }
        Type::Bytes => {
            if f.optional {
                "&'a [u8]? ! DecodeError".to_string()
            } else {
                "&'a [u8] ! DecodeError".to_string()
            }
        }
        Type::Message(id) => format!("{}<'a>? ! DecodeError", view_ref(schema, m, id)),
        Type::List(elem) => match elem {
            ElemType::Scalar(s) => format!("ScalarList<'a, {}> ! DecodeError", aki_scalar(s)),
            ElemType::Enum(id) => {
                format!("ScalarList<'a, {}> ! DecodeError", enum_ref(schema, m, id))
            }
            ElemType::String | ElemType::Bytes => "OffsetList<'a> ! DecodeError".to_string(),
            ElemType::Message(id) => format!("{}<'a> ! DecodeError", view_list_ref(schema, m, id)),
        },
    }
}

fn to_owned_and_view_methods(w: &mut CodeWriter, schema: &Schema, m: &Message, name: &str) {
    let view = format!("{name}View");
    let list = format!("{name}ViewList");
    w.blank();
    w.open(format!(
        "fn {view}::parse(data: &'a [u8]): {view}<'a> ! DecodeError {{"
    ));
    w.line("let parsed = try View::parse(data);");
    w.line(format!("return {view} {{ view: parsed }};"));
    w.close("}");
    for f in &m.fields {
        w.blank();
        view_accessor(w, schema, m, f, &view);
    }
    w.blank();
    w.open(format!(
        "fn {view}::to_owned(self&): {name} ! DecodeError {{"
    ));
    w.line(format!("var out = {name} {{}};"));
    for f in &m.fields {
        to_owned_field(w, schema, m, f);
    }
    w.line("return out;");
    w.close("}");

    w.blank();
    w.open(format!(
        "fn {list}::get(self&, i: usize): {view}<'a> ! DecodeError {{"
    ));
    w.line("let child = try self.list.message_at(i);");
    w.line(format!("return {view} {{ view: child }};"));
    w.close("}");

    w.blank();
    w.open(format!(
        "fn {list}::to_owned(self&): List<{name}> ! DecodeError {{"
    ));
    w.line(format!("var out = List::<{name}>();"));
    w.open("for (let i in 0..self.len()) {");
    w.line("let item = try self.get(i);");
    w.line("let owned = try item.to_owned();");
    w.line("out.push(owned);");
    w.close("}");
    w.line("return out;");
    w.close("}");
}

/// Emits the body of one view accessor.
fn view_accessor(w: &mut CodeWriter, schema: &Schema, m: &Message, f: &Field, view: &str) {
    let method = accessor_name(f);
    let ret = accessor_type(schema, m, f);
    w.open(format!("fn {view}::{method}(self&): {ret} {{"));
    match (f.layout.data, f.ty) {
        (DataSlot::Bit(bit), _) => {
            if let Some(p) = f.layout.presence {
                w.open(format!("if (!self.view.bit_at({}, {})) {{", p.byte, p.bit));
                w.line("return none;");
                w.close("}");
            }
            w.line(format!(
                "return self.view.bit_at({}, {});",
                bit.byte, bit.bit
            ));
        }
        (DataSlot::Bytes { offset, .. }, ty) => {
            let (reader, wrap) = match ty {
                Type::Scalar(s) => (format!("{}_at", s.name()), None),
                Type::Enum(id) => {
                    let backing = schema.enumeration(id).backing;
                    (
                        format!("{}_at", backing.name()),
                        Some(enum_ref(schema, m, id)),
                    )
                }
                _ => unreachable!("byte slots hold scalars and enums"),
            };
            let value = match wrap {
                Some(ty) => format!("(self.view.{reader}({offset})) as {ty}"),
                None => format!("self.view.{reader}({offset})"),
            };
            if let Some(p) = f.layout.presence {
                w.open(format!("if (!self.view.bit_at({}, {})) {{", p.byte, p.bit));
                w.line("return none;");
                w.close("}");
            }
            w.line(format!("return {value};"));
        }
        (DataSlot::Offset { offset }, Type::String) => {
            w.line(format!("let value = try self.view.str_at({offset});"));
            if f.optional {
                w.line("return value;");
            } else {
                w.open("if (let s = value) {");
                w.line("return s;");
                w.close("}");
                w.line("return \"\";");
            }
        }
        (DataSlot::Offset { offset }, Type::Bytes) => {
            if f.optional {
                w.line(format!(
                    "let value = try self.view.bytes_or_absent({offset});"
                ));
            } else {
                w.line(format!("let value = try self.view.bytes_at({offset});"));
            }
            w.line("return value;");
        }
        (DataSlot::Offset { offset }, Type::Message(id)) => {
            let child = view_ref(schema, m, id);
            w.line(format!("let value = try self.view.message_at({offset});"));
            w.open("if (let c = value) {");
            w.line(format!("return {child} {{ view: c }};"));
            w.close("}");
            w.line("return none;");
        }
        (DataSlot::Offset { offset }, Type::List(elem)) => match elem {
            ElemType::Scalar(s) => {
                w.line(format!(
                    "let list = try self.view.scalar_list_at({offset}, {}, {});",
                    element_size(s),
                    element_reader(s)
                ));
                w.line("return list;");
            }
            ElemType::Enum(id) => {
                let e = schema.enumeration(id);
                w.line(format!(
                    "let list = try self.view.scalar_list_at({offset}, {}, {});",
                    e.backing.size(),
                    enum_reader(e)
                ));
                w.line("return list;");
            }
            ElemType::String | ElemType::Bytes => {
                w.line(format!(
                    "let list = try self.view.offset_list_at({offset});"
                ));
                w.line("return list;");
            }
            ElemType::Message(id) => {
                let list = view_list_ref(schema, m, id);
                w.line(format!(
                    "let list = try self.view.offset_list_at({offset});"
                ));
                w.line(format!("return {list} {{ list: list }};"));
            }
        },
        (slot, ty) => unreachable!("invalid slot {slot:?} for type {ty:?}"),
    }
    w.close("}");
}

/// Emits the statements that copy one view field into `out`.
fn to_owned_field(w: &mut CodeWriter, schema: &Schema, m: &Message, f: &Field) {
    let field = aki_ident(&f.name);
    let method = accessor_name(f);
    match f.ty {
        Type::Scalar(_) | Type::Enum(_) => {
            w.line(format!("out.{field} = self.{method}();"));
        }
        Type::String => {
            w.line(format!("let {field}_text = try self.{method}();"));
            if f.optional {
                w.open(format!("if (let s = {field}_text) {{"));
                w.line(format!("out.{field} = from_str(s);"));
                w.close("}");
            } else {
                w.line(format!("out.{field} = from_str({field}_text);"));
            }
        }
        Type::Bytes => {
            w.line(format!("let {field}_bytes = try self.{method}();"));
            if f.optional {
                w.open(format!("if (let b = {field}_bytes) {{"));
                w.line(format!("out.{field} = to_list(b);"));
                w.close("}");
            } else {
                w.line(format!("out.{field} = to_list({field}_bytes);"));
            }
        }
        Type::Message(id) => {
            w.line(format!("let {field}_view = try self.{method}();"));
            w.open(format!("if (let c = {field}_view) {{"));
            w.line("let child = try c.to_owned();");
            if f.boxed {
                let child_type = message_ref(schema, m, id);
                w.line(format!("out.{field} = Box::<{child_type}>(child);"));
            } else {
                w.line(format!("out.{field} = child;"));
            }
            w.close("}");
        }
        Type::List(elem) => {
            w.line(format!("let {field}_list = try self.{method}();"));
            match elem {
                ElemType::Scalar(_) | ElemType::Enum(_) => {
                    w.line(format!("out.{field} = {field}_list.to_list();"));
                }
                ElemType::String => {
                    w.line(format!("out.{field} = try {field}_list.to_strings();"));
                }
                ElemType::Bytes => {
                    w.line(format!("out.{field} = try {field}_list.to_bytes();"));
                }
                ElemType::Message(_) => {
                    w.line(format!("out.{field} = try {field}_list.to_owned();"));
                }
            }
        }
    }
}
